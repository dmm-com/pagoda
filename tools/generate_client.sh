#!/bin/bash

set -euo pipefail

# Share the pinned generator version with the local npm wrapper.
OPENAPI_GENERATOR_VERSION=$(node -p 'require("./openapitools.json")["generator-cli"].version') || exit 1
if [[ ! "$OPENAPI_GENERATOR_VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  echo "Invalid generator version in openapitools.json" >&2
  exit 1
fi
dst=${1:-frontend/src/apiclient/autogenerated}

# Check if "--docker" is passed as an argument
if [[ "${*:-}" == *"--docker"* ]]; then
  SPECTACULAR_CMD=(docker compose exec -e "DJANGO_CONFIGURATION=${DJANGO_CONFIGURATION:-}" -w /workspace/airone airone bash -lc "uv run python manage.py spectacular")
  GENERATE_CMD=(docker run --rm -u "$(id -u):$(id -g)" -v "${PWD}:/local" "openapitools/openapi-generator-cli:v$OPENAPI_GENERATOR_VERSION" generate -i /local/spec.yaml -g typescript-fetch -o /local/"$dst" --additional-properties=typescriptThreePlus=true)
  PRETTIER_CMD=(docker compose exec -w /workspace/airone airone bash -lc "npx prettier --write $dst")
else
  SPECTACULAR_CMD=(uv run python manage.py spectacular)
  # Use the npm wrapper (runs the same Java jar) so no docker daemon is required,
  # e.g. inside the dev container. The generator version is pinned by openapitools.json.
  GENERATE_CMD=(npx --yes @openapitools/openapi-generator-cli generate -i spec.yaml -g typescript-fetch -o "$dst" --additional-properties=typescriptThreePlus=true)
  PRETTIER_CMD=(npx prettier --write "$dst")
fi

# Generate the OpenAPI spec and capture stderr. A non-zero exit means the
# command itself crashed (import error, bad settings, ...) and must fail the run
# instead of being masked by a later step.
spec_err=$(mktemp)
trap 'rm -f "$spec_err"' EXIT

if ! "${SPECTACULAR_CMD[@]}" > spec.yaml 2> "$spec_err"; then
  echo "Error(s) occur on generating OpenAPI spec from API implementation:"
  cat "$spec_err"
  exit 1
fi

# Spectacular reports per-view errors on stderr without failing the command.
# Match both "Error [ViewName]: ..." (with breadcrumbs) and plain "Error: ..."
# lines, allowing the optional "source:line: " prefix Spectacular adds.
# Requiring a boundary before "Error" avoids matching exception names such as
# "ImportError:".
generr=$(grep -E '(^|[[:space:]])Error(:| \[)' "$spec_err" || true)
if [ -n "$generr" ]; then
  echo "Error(s) occur on generating OpenAPI spec from API implementation:"
  echo "$generr"
  exit 1
fi

# generate client code
"${GENERATE_CMD[@]}"

# format client code
"${PRETTIER_CMD[@]}"

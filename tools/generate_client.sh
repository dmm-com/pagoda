#!/bin/bash

set -u

OPENAPI_GENERATOR_VERSION=v7.8.0
dst=${1:-frontend/src/apiclient/autogenerated}

# Check if "--docker" is passed as an argument
if [[ $@ == *"--docker"* ]]; then
  CHECK_CMD="docker compose exec -e DJANGO_CONFIGURATION=${DJANGO_CONFIGURATION:-} -w /workspace/airone airone bash -lc 'uv run python manage.py spectacular 2>&1 > /dev/null | grep ERROR'"
  SPECTACULAR_CMD="docker compose exec -e DJANGO_CONFIGURATION=${DJANGO_CONFIGURATION:-} -w /workspace/airone airone bash -lc 'uv run python manage.py spectacular --file spec.yaml'"
  GENERATE_CMD="docker run --rm -u \"$(id -u):$(id -g)\" -v \"${PWD}:/local\" openapitools/openapi-generator-cli:$OPENAPI_GENERATOR_VERSION generate -i /local/spec.yaml -g typescript-fetch -o /local/\"$dst\" --additional-properties=typescriptThreePlus=true"
  PRETTIER_CMD="docker compose exec -w /workspace/airone airone bash -lc 'npx prettier --write $dst'"
else
  CHECK_CMD="uv run python manage.py spectacular 2>&1 > /dev/null | grep ERROR"
  SPECTACULAR_CMD="uv run python manage.py spectacular --file spec.yaml"
  # Use the npm wrapper (runs the same Java jar) so no docker daemon is required,
  # e.g. inside the dev container. The generator version is pinned by openapitools.json.
  GENERATE_CMD="npx --yes @openapitools/openapi-generator-cli generate -i spec.yaml -g typescript-fetch -o $dst --additional-properties=typescriptThreePlus=true"
  PRETTIER_CMD="npx prettier --write $dst"
fi


# detect errors on spectacular
generr=$(eval $CHECK_CMD)
if [ "$generr" != "" ]; then
  echo "Error(s) occur on generating OpenAPI spec from API implementation:";
  echo "$generr";
  exit 1;
fi

# generate OpenAPI spec
eval $SPECTACULAR_CMD;

# generate client code
eval $GENERATE_CMD;

# format client code
eval $PRETTIER_CMD;

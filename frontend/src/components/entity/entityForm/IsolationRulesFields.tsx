import DeleteOutlineIcon from "@mui/icons-material/DeleteOutline";
import {
  Autocomplete,
  Box,
  Checkbox,
  IconButton,
  MenuItem,
  Select,
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableRow,
  TextField,
  Typography,
} from "@mui/material";
import { styled } from "@mui/material/styles";
import { FC, Fragment } from "react";
import { Control, Controller, useFieldArray, useWatch } from "react-hook-form";

import { Schema } from "./EntityFormSchema";

import { Entity } from "apiclient/autogenerated";
import {
  AddRowButton,
  AppendRow,
  InsertBand,
  InsertBandRow,
  useInsertedRowFocus,
} from "components/common/RowInsertion";
import { ReferralsAutocomplete } from "components/entry/entryForm/ReferralsAutocomplete";
import { useTranslation } from "hooks/useTranslation";
import { BaseAttributeTypes } from "services/Constants";
import { fuzzyMatch } from "services/StringUtil";

// Attribute types supported in isolation conditions (same as trigger conditions)
const ISOLATION_SUPPORTED_TYPES = [
  BaseAttributeTypes.string,
  BaseAttributeTypes.string | BaseAttributeTypes.array,
  BaseAttributeTypes.bool,
  BaseAttributeTypes.object,
  BaseAttributeTypes.object | BaseAttributeTypes.array,
  BaseAttributeTypes.object | BaseAttributeTypes.named,
  BaseAttributeTypes.object |
    BaseAttributeTypes.named |
    BaseAttributeTypes.array,
];

const HeaderTableRow = styled(TableRow)(() => ({
  backgroundColor: "#455A64",
}));

const HeaderTableCell = styled(TableCell)(() => ({
  color: "#FFFFFF",
  boxSizing: "border-box",
}));

const StyledTableRow = styled(TableRow)(() => ({
  "& td": {
    padding: "8px",
    verticalAlign: "top",
  },
}));

interface Props {
  control: Control<Schema>;
  referralEntities: Entity[];
}

interface ConditionValueProps {
  ruleIndex: number;
  condIndex: number;
  attrType: number;
  attrId: number | undefined;
  control: Control<Schema>;
}

const IsolationConditionValue: FC<ConditionValueProps> = ({
  ruleIndex,
  condIndex,
  attrType,
  attrId,
  control,
}) => {
  const { t } = useTranslation();
  const isObject = (attrType & BaseAttributeTypes.object) !== 0;
  const isNamed = isObject && (attrType & BaseAttributeTypes.named) !== 0;
  const isBool = (attrType & BaseAttributeTypes.bool) !== 0;

  if (isBool) {
    return (
      <Controller
        name={`isolationRules.${ruleIndex}.conditions.${condIndex}.boolCond`}
        control={control}
        render={({ field }) => (
          <Checkbox
            checked={field.value}
            onChange={(e) => field.onChange(e.target.checked)}
          />
        )}
      />
    );
  }

  if (isNamed) {
    return (
      <Box display="flex" gap={1} alignItems="flex-end">
        <Controller
          name={`isolationRules.${ruleIndex}.conditions.${condIndex}.strCond`}
          control={control}
          render={({ field }) => (
            <TextField
              {...field}
              value={field.value ?? ""}
              variant="standard"
              placeholder={t("entity.form.isolationNamePlaceholder")}
              size="small"
            />
          )}
        />
        {attrId != null && (
          <Box flexGrow={1}>
            <Controller
              name={`isolationRules.${ruleIndex}.conditions.${condIndex}.refCond`}
              control={control}
              render={({ field }) => (
                <ReferralsAutocomplete
                  attrId={attrId}
                  value={field.value}
                  handleChange={(v) => field.onChange(v)}
                  multiple={false}
                />
              )}
            />
          </Box>
        )}
      </Box>
    );
  }

  if (isObject) {
    if (attrId == null) return null;
    return (
      <Controller
        name={`isolationRules.${ruleIndex}.conditions.${condIndex}.refCond`}
        control={control}
        render={({ field }) => (
          <ReferralsAutocomplete
            attrId={attrId}
            value={field.value}
            handleChange={(v) => field.onChange(v)}
            multiple={false}
          />
        )}
      />
    );
  }

  // string / text / array_string
  return (
    <Controller
      name={`isolationRules.${ruleIndex}.conditions.${condIndex}.strCond`}
      control={control}
      render={({ field }) => (
        <TextField
          {...field}
          value={field.value ?? ""}
          variant="standard"
          fullWidth
          size="small"
        />
      )}
    />
  );
};

interface ConditionsCellProps {
  ruleIndex: number;
  control: Control<Schema>;
  savedAttrs: Array<{ id?: number; name: string; type: number }>;
}

const IsolationConditionsCell: FC<ConditionsCellProps> = ({
  ruleIndex,
  control,
  savedAttrs,
}) => {
  const { fields, insert, remove } = useFieldArray({
    control,
    name: `isolationRules.${ruleIndex}.conditions`,
    keyName: "key",
  });

  const emptyCondition = () => ({
    id: undefined,
    attr: { id: 0, name: "", type: 0 },
    strCond: null,
    refCond: null,
    boolCond: false,
    isUnmatch: false,
  });

  const { t } = useTranslation();
  const listId = `isolation-conditions-${ruleIndex}`;
  const focusInsertedRow = useInsertedRowFocus(listId);

  const handleInsertCondition = (index: number) => {
    insert(index, emptyCondition());
    focusInsertedRow(index);
  };

  return (
    <Box data-testid={listId}>
      {fields.map((condField, condIndex) => (
        <Fragment key={condField.key}>
          <InsertBand
            index={condIndex}
            ariaLabel={t("entity.form.insertIsolationConditionBefore", {
              row: condIndex + 1,
            })}
            onInsert={handleInsertCondition}
            testId={`insert-band-isolation-condition-${ruleIndex}-${condIndex}`}
            dense
          />
          <IsolationConditionRow
            ruleIndex={ruleIndex}
            listId={listId}
            condIndex={condIndex}
            control={control}
            savedAttrs={savedAttrs}
            onRemove={() => remove(condIndex)}
          />
        </Fragment>
      ))}
      <AddRowButton
        onAdd={() => handleInsertCondition(fields.length)}
        label={t("entity.form.appendIsolationCondition")}
        ariaLabel={t("entity.form.appendIsolationConditionAriaLabel", {
          rule: ruleIndex + 1,
        })}
        testId={`append-isolation-condition-${ruleIndex}`}
      />
    </Box>
  );
};

interface ConditionRowProps {
  ruleIndex: number;
  listId: string;
  condIndex: number;
  control: Control<Schema>;
  savedAttrs: Array<{ id?: number; name: string; type: number }>;
  onRemove: () => void;
}

const IsolationConditionRow: FC<ConditionRowProps> = ({
  ruleIndex,
  listId,
  condIndex,
  control,
  savedAttrs,
  onRemove,
}) => {
  const { t } = useTranslation();
  const attrId = useWatch({
    control,
    name: `isolationRules.${ruleIndex}.conditions.${condIndex}.attr.id`,
  });
  const selectedAttr = savedAttrs.find((a) => a.id === attrId);

  return (
    <Box
      display="flex"
      gap={1}
      alignItems="center"
      data-list-id={listId}
      data-row-index={condIndex}
    >
      <Controller
        name={`isolationRules.${ruleIndex}.conditions.${condIndex}.attr.id`}
        control={control}
        render={({ field }) => (
          <Select
            value={field.value || 0}
            id={`isolation-attr-${ruleIndex}-${condIndex}`}
            labelId="isolation-attr-header"
            onChange={(e) => {
              const found = savedAttrs.find(
                (a) => a.id === Number(e.target.value),
              );
              field.onChange(Number(e.target.value));
              // Reset value fields when attr changes
              if (found) {
                // type change is handled by watching attrId
              }
            }}
            size="small"
            sx={{ minWidth: 200 }}
          >
            <MenuItem value={0} disabled>
              {t("entity.form.isolationSelectAttrPlaceholder")}
            </MenuItem>
            {savedAttrs
              .filter((a) => ISOLATION_SUPPORTED_TYPES.includes(a.type))
              .map((a) => (
                <MenuItem key={a.id} value={a.id}>
                  {a.name}
                </MenuItem>
              ))}
          </Select>
        )}
      />

      <Controller
        name={`isolationRules.${ruleIndex}.conditions.${condIndex}.isUnmatch`}
        control={control}
        render={({ field }) => (
          <Checkbox
            size="small"
            checked={field.value}
            onChange={(e) => field.onChange(e.target.checked)}
            title="NOT"
          />
        )}
      />

      <Box flexGrow={1} minWidth={150}>
        {selectedAttr && selectedAttr.type !== 0 ? (
          <IsolationConditionValue
            ruleIndex={ruleIndex}
            condIndex={condIndex}
            attrType={selectedAttr.type}
            attrId={selectedAttr.id}
            control={control}
          />
        ) : (
          <TextField
            variant="standard"
            fullWidth
            size="small"
            disabled
            placeholder={t("entity.form.isolationValuePlaceholder")}
          />
        )}
      </Box>

      <IconButton
        size="small"
        data-testid={`delete-isolation-condition-${ruleIndex}-${condIndex}`}
        aria-label={t("entity.form.deleteIsolationCondition", {
          row: condIndex + 1,
        })}
        onClick={onRemove}
      >
        <DeleteOutlineIcon />
      </IconButton>
    </Box>
  );
};

interface RuleRowProps {
  ruleIndex: number;
  control: Control<Schema>;
  savedAttrs: Array<{ id?: number; name: string; type: number }>;
  referralEntities: Entity[];
  onRemove: () => void;
}

const IsolationRuleRow: FC<RuleRowProps> = ({
  ruleIndex,
  control,
  savedAttrs,
  referralEntities,
  onRemove,
}) => {
  const { t } = useTranslation();
  const isPreventAll = useWatch({
    control,
    name: `isolationRules.${ruleIndex}.action.isPreventAll`,
  });

  return (
    <StyledTableRow data-list-id="isolation-rules" data-row-index={ruleIndex}>
      <TableCell>
        <Controller
          name={`isolationRules.${ruleIndex}.action.preventFrom`}
          control={control}
          render={({ field }) => (
            <Autocomplete
              options={referralEntities}
              getOptionLabel={(opt) => opt.name}
              filterOptions={(options, state) =>
                options.filter((option) =>
                  fuzzyMatch(option.name, state.inputValue),
                )
              }
              isOptionEqualToValue={(opt, val) => opt.id === val.id}
              value={field.value ?? null}
              onChange={(_e, val) => field.onChange(val)}
              disabled={isPreventAll}
              size="small"
              sx={{ minWidth: 150 }}
              renderInput={(params) => (
                <TextField
                  {...params}
                  placeholder={t("entity.form.selectEntityPlaceholder")}
                  size="small"
                />
              )}
            />
          )}
        />
      </TableCell>

      <TableCell>
        <Controller
          name={`isolationRules.${ruleIndex}.action.isPreventAll`}
          control={control}
          render={({ field }) => (
            <Checkbox
              checked={field.value}
              onChange={(e) => field.onChange(e.target.checked)}
            />
          )}
        />
      </TableCell>

      <TableCell>
        <IsolationConditionsCell
          ruleIndex={ruleIndex}
          control={control}
          savedAttrs={savedAttrs}
        />
      </TableCell>

      <TableCell>
        <IconButton
          data-testid={`delete-isolation-rule-${ruleIndex}`}
          aria-label={t("entity.form.deleteIsolationRule", {
            row: ruleIndex + 1,
          })}
          onClick={onRemove}
        >
          <DeleteOutlineIcon />
        </IconButton>
      </TableCell>
    </StyledTableRow>
  );
};

const emptyRule = () => ({
  id: undefined,
  conditions: [],
  action: {
    id: undefined,
    isPreventAll: false,
    preventFrom: null,
  },
});

export const IsolationRulesFields: FC<Props> = ({
  control,
  referralEntities,
}) => {
  const { t } = useTranslation();
  const { fields, insert, remove } = useFieldArray({
    control,
    name: "isolationRules",
    keyName: "key",
  });

  const formAttrs = useWatch({ control, name: "attrs" });
  const savedAttrs = (formAttrs ?? []).filter((a) => a.id !== undefined);

  const focusInsertedRow = useInsertedRowFocus("isolation-rules");

  const handleInsertRule = (index: number) => {
    insert(index, emptyRule());
    focusInsertedRow(index);
  };

  return (
    <>
      <Typography variant="h4" align="center" my="16px">
        {t("entity.form.isolationTitle")}
      </Typography>

      <Table id="table_isolation_rules_list">
        <TableHead>
          <HeaderTableRow>
            <HeaderTableCell width="200px">
              {t("entity.form.isolationTargetEntityHeader")}
            </HeaderTableCell>
            <HeaderTableCell width="100px">
              {t("entity.form.isolationAllEntitiesHeader")}
            </HeaderTableCell>
            <HeaderTableCell sx={{ display: "flex", gap: "8px" }}>
              <Box width="200px" id="isolation-attr-header">
                {t("entity.form.isolationAttrHeader")}
              </Box>
              <Box>NOT</Box>
              <Box>{t("entity.form.isolationExcludeValueHeader")}</Box>
            </HeaderTableCell>
            <HeaderTableCell width="60px">{t("common.delete")}</HeaderTableCell>
          </HeaderTableRow>
        </TableHead>
        <TableBody>
          {fields.map((rule, ruleIndex) => (
            <Fragment key={rule.key}>
              <InsertBandRow
                colSpan={4}
                index={ruleIndex}
                ariaLabel={t("entity.form.insertIsolationRuleBefore", {
                  row: ruleIndex + 1,
                })}
                onInsert={handleInsertRule}
                testId={`insert-band-isolation-rule-${ruleIndex}`}
              />
              <IsolationRuleRow
                ruleIndex={ruleIndex}
                control={control}
                savedAttrs={savedAttrs}
                referralEntities={referralEntities}
                onRemove={() => remove(ruleIndex)}
              />
            </Fragment>
          ))}
          <AppendRow
            colSpan={4}
            onAdd={() => handleInsertRule(fields.length)}
            label={t("entity.form.appendIsolationRule")}
            testId="append-row-isolation-rule"
          />
        </TableBody>
      </Table>
    </>
  );
};

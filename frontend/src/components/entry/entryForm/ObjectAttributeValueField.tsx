import DeleteOutlineIcon from "@mui/icons-material/DeleteOutline";
import {
  Box,
  Checkbox,
  IconButton,
  List,
  ListItem,
  TextField,
  Typography,
} from "@mui/material";
import { styled } from "@mui/material/styles";
import { FC, Fragment, useEffect, useState } from "react";
import { Control, Controller, useFieldArray } from "react-hook-form";
import { UseFormSetValue } from "react-hook-form";

import { Schema } from "./EntryFormSchema";
import { ReferralsAutocomplete } from "./ReferralsAutocomplete";

import { GetEntryAttrReferral } from "apiclient/autogenerated";
import {
  AddRowButton,
  InsertBand,
  useInsertedRowFocus,
} from "components/common/RowInsertion";
import { useTranslation } from "hooks/useTranslation";
import { getStagedErrorStyle } from "utils/styleUtils";

const StyledList = styled(List)(({}) => ({
  padding: "0",
}));

const StyledTypography = styled(Typography)(({}) => ({
  color: "rgba(0, 0, 0, 0.6)",
}));

const StyledBox = styled(Box)(({}) => ({
  display: "flex",
  alignItems: "center",
}));

const NamedObjectBox = styled(Box)(({}) => ({
  display: "flex",
  alignItems: "flex-end",
  gap: "0 12px",
  width: "100%",
}));

const FlexBox = styled(Box)(({}) => ({
  display: "flex",
  flexDirection: "column",
}));

const NameBox = styled(Box)(({}) => ({
  width: "280px",
}));

const BooleanBox = styled(Box)(({}) => ({
  display: "flex",
  flexDirection: "column",
  width: "60px",
}));

interface CommonProps {
  attrId: number;
  control: Control<Schema>;
  setValue: UseFormSetValue<Schema>;
  isDisabled?: boolean;
  /** Shown in accessible names so repeated lists stay distinguishable. */
  attrName?: string;
}

export const ObjectAttributeValueField: FC<
  CommonProps & {
    multiple?: boolean;
  }
> = ({ multiple, attrId, control, setValue, isDisabled = false }) => {
  const [hasRestrictedItems, setHasRestrictedItems] = useState(false);
  const { t } = useTranslation();

  const handleChange = (
    value: GetEntryAttrReferral | GetEntryAttrReferral[] | null,
  ) => {
    const newValue = (() => {
      if (value == null) {
        return null;
      }
      if (multiple === true) {
        const _value = value as GetEntryAttrReferral[];
        return _value.map((v) => ({
          ...v,
          _boolean: false,
        }));
      } else {
        const _value = value as GetEntryAttrReferral;
        return {
          ..._value,
          _boolean: false,
        };
      }
    })();

    setValue(
      multiple
        ? `attrs.${attrId}.value.asArrayObject`
        : `attrs.${attrId}.value.asObject`,
      newValue as never,
      {
        shouldDirty: true,
        shouldValidate: true,
      },
    );
  };

  return (
    <Box>
      <StyledBox>
        <StyledTypography variant="caption">
          {t("entryForm.objectField.selectItem")}
        </StyledTypography>
        {hasRestrictedItems && (
          <StyledTypography variant="caption" sx={{ color: "error.main" }}>
            {t("entryForm.objectField.restrictedItemsNote")}
          </StyledTypography>
        )}
      </StyledBox>
      <Controller
        name={
          multiple
            ? `attrs.${attrId}.value.asArrayObject`
            : `attrs.${attrId}.value.asObject`
        }
        control={control}
        render={({ field, fieldState: { error } }) => (
          <ReferralsAutocomplete
            attrId={attrId}
            value={field.value ?? null}
            handleChange={handleChange}
            multiple={multiple}
            error={error}
            isDisabled={isDisabled}
            onRestrictedItemsChange={setHasRestrictedItems}
          />
        )}
      />
    </Box>
  );
};

export const NamedObjectAttributeValueField: FC<
  CommonProps & {
    index?: number;
    handleClickDeleteListItem?: (index: number) => void;
    withBoolean?: boolean;
  }
> = ({
  attrId,
  index,
  control,
  setValue,
  handleClickDeleteListItem,
  withBoolean,
}) => {
  const [hasRestrictedItems, setHasRestrictedItems] = useState(false);
  const { t } = useTranslation();

  const handleChange = (
    value: GetEntryAttrReferral | GetEntryAttrReferral[] | null,
  ) => {
    const newValue = (() => {
      if (Array.isArray(value)) {
        throw new Error("Array typed value is not supported for named object.");
      }

      if (value == null) {
        return null;
      } else {
        const _value = value as GetEntryAttrReferral;
        return {
          ..._value,
          _boolean: false,
        };
      }
    })();

    setValue(
      index != null
        ? `attrs.${attrId}.value.asArrayNamedObject.${index}.object`
        : `attrs.${attrId}.value.asNamedObject.object`,
      newValue as never,
      {
        shouldDirty: true,
        shouldValidate: true,
      },
    );
  };

  return (
    <NamedObjectBox>
      <FlexBox>
        <StyledTypography variant="caption">name</StyledTypography>
        <NameBox>
          <Controller
            name={
              index != null
                ? `attrs.${attrId}.value.asArrayNamedObject.${index}.name`
                : `attrs.${attrId}.value.asNamedObject.name`
            }
            control={control}
            defaultValue=""
            render={({ field, fieldState: { error, isDirty } }) => (
              <TextField
                {...field}
                variant="standard"
                fullWidth
                error={error != null}
                helperText={error?.message}
                sx={getStagedErrorStyle(!!error, isDirty)}
              />
            )}
          />
        </NameBox>
      </FlexBox>
      {withBoolean === true && (
        <BooleanBox>
          <StyledTypography variant="caption">
            {t("entryForm.objectField.disabled")}
          </StyledTypography>
          <Controller
            name={`attrs.${attrId}.value.asArrayNamedObject.${index}._boolean`}
            control={control}
            render={({ field }) => (
              <Checkbox
                checked={field.value ?? false}
                onChange={(e) => field.onChange(e.target.checked)}
              />
            )}
          />
        </BooleanBox>
      )}
      <Box flexGrow={1}>
        <Box display="flex" alignItems="center" gap={1}>
          <StyledTypography variant="caption">
            {t("entryForm.objectField.selectItem")}
          </StyledTypography>
          {hasRestrictedItems && (
            <StyledTypography variant="caption" sx={{ color: "error.main" }}>
              {t("entryForm.objectField.restrictedItemsNote")}
            </StyledTypography>
          )}
        </Box>
        <Controller
          name={
            index != null
              ? `attrs.${attrId}.value.asArrayNamedObject.${index}.object`
              : `attrs.${attrId}.value.asNamedObject.object`
          }
          control={control}
          render={({ field, fieldState: { error } }) => (
            <ReferralsAutocomplete
              attrId={attrId}
              value={field.value ?? null}
              handleChange={handleChange}
              error={error}
              onRestrictedItemsChange={setHasRestrictedItems}
            />
          )}
        />
      </Box>
      {index !== undefined && handleClickDeleteListItem != null && (
        <IconButton
          data-testid={`delete-row-${attrId}-${index}`}
          aria-label={t("entryForm.array.deleteRow", { row: index + 1 })}
          onClick={() => handleClickDeleteListItem(index)}
        >
          <DeleteOutlineIcon />
        </IconButton>
      )}
    </NamedObjectBox>
  );
};

export const ArrayNamedObjectAttributeValueField: FC<
  CommonProps & {
    withBoolean?: boolean;
  }
> = ({ attrId, control, setValue, withBoolean, attrName }) => {
  const { fields, insert, remove, replace } = useFieldArray({
    control,
    name: `attrs.${attrId}.value.asArrayNamedObject`,
  });
  const { t } = useTranslation();
  const listId = `array-named-object-${attrId}`;
  const focusInsertedRow = useInsertedRowFocus(listId);

  const handleInsertListItem = (index: number) => {
    insert(index, { name: "", object: null, _boolean: false });
    focusInsertedRow(index);
  };

  // Keep at least one (empty) row. This must not run during render: it
  // updates form state owned by the parent form component. `replace` keeps
  // it idempotent when StrictMode runs the effect twice.
  useEffect(() => {
    if (fields.length === 0) {
      replace([{ name: "", object: null, _boolean: false }]);
    }
  }, [fields.length, replace]);

  return (
    <StyledList data-testid={`array-named-object-list-${attrId}`}>
      {fields.map((field, index) => (
        <Fragment key={field.id}>
          <ListItem disablePadding>
            <InsertBand
              index={index}
              ariaLabel={
                attrName != null
                  ? t("entryForm.array.insertBefore", {
                      name: attrName,
                      row: index + 1,
                    })
                  : t("entryForm.array.insertBeforeNoName", { row: index + 1 })
              }
              onInsert={handleInsertListItem}
              testId={`insert-band-${attrId}-${index}`}
            />
          </ListItem>
          <ListItem disablePadding data-list-id={listId} data-row-index={index}>
            <NamedObjectAttributeValueField
              control={control}
              setValue={setValue}
              attrId={attrId}
              index={index}
              handleClickDeleteListItem={remove}
              withBoolean={withBoolean}
            />
          </ListItem>
        </Fragment>
      ))}
      <ListItem disablePadding>
        <AddRowButton
          onAdd={() => handleInsertListItem(fields.length)}
          label={t("entryForm.array.appendNoName")}
          ariaLabel={
            attrName != null
              ? t("entryForm.array.append", { name: attrName })
              : undefined
          }
          testId={`append-row-${attrId}`}
        />
      </ListItem>
    </StyledList>
  );
};

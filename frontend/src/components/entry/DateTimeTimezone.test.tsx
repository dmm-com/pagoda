import { fireEvent, render, screen, waitFor } from "@testing-library/react";
import { http, HttpResponse } from "msw";
import { setupServer } from "msw/node";
import { createMemoryRouter, RouterProvider } from "react-router";

import { AttributeValue } from "./AttributeValue";
import { SearchResultControlMenu } from "./SearchResultControlMenu";

import { TestWrapper, TestWrapperWithoutRoutes } from "TestWrapper";
import {
  AdvancedSearchResultAttrInfoFilterKeyEnum as FilterKey,
  EntryAttributeTypeTypeEnum,
} from "apiclient/autogenerated";
import { EntryEditPage } from "pages/EntryEditPage";
import { entityEntriesPath, newEntryPath } from "routes/Routes";
import { AttrFilter } from "services/entry/AdvancedSearch";

const winter = "2025-01-15T23:15:27.000Z";
const summer = "2025-07-15T23:45:38.000Z";
const localFormat = new Intl.DateTimeFormat("ja-JP", {
  year: "numeric",
  month: "2-digit",
  day: "2-digit",
  hour: "2-digit",
  minute: "2-digit",
  second: "2-digit",
  hourCycle: "h23",
});
const localText = (iso: string) => localFormat.format(new Date(iso));

const filters = [
  {
    label: "include",
    index: 0,
    key: FilterKey.TEXT_CONTAINED,
    instant: winter,
    stored: "2025-01-15T23:15:27.123Z",
  },
  {
    label: "exclude",
    index: 1,
    key: FilterKey.TEXT_NOT_CONTAINED,
    instant: summer,
    stored: "2025-07-15T23:45:38.999Z",
  },
];

function openMenu(
  attrFilter?: AttrFilter,
  attrType: EntryAttributeTypeTypeEnum = EntryAttributeTypeTypeEnum.DATETIME,
) {
  const onSelect = vi.fn();
  const view = render(
    <SearchResultControlMenu
      attrname="timestamp"
      attrFilter={attrFilter}
      attrType={attrType}
      anchorElem={document.createElement("button")}
      handleUpdateAttrFilter={vi.fn()}
      handleSelectFilterConditions={onSelect}
      handleClose={vi.fn()}
      setOpenEditModal={vi.fn()}
      isDisabledEditModal={false}
      entityAttrs={[]}
      totalCount={1}
    />,
    { wrapper: TestWrapper },
  );
  return { onSelect, unmount: view.unmount };
}

test("reopens calendar date filters on the same day in the browser timezone", () => {
  const { unmount } = openMenu(
    { filterKey: FilterKey.TEXT_CONTAINED, keyword: "2025-01-15" },
    EntryAttributeTypeTypeEnum.DATE,
  );
  expect(screen.getAllByRole("textbox")[0]).toHaveValue("2025/01/15");
  unmount();

  openMenu(
    {
      filterKey: FilterKey.TEXT_NOT_CONTAINED,
      keyword: "2025-01-15~2025-01-16",
    },
    EntryAttributeTypeTypeEnum.DATE,
  );
  expect(screen.getAllByRole("textbox", { name: "開始日" })[1]).toHaveValue(
    "2025/01/15",
  );
  expect(screen.getAllByRole("textbox", { name: "終了日" })[1]).toHaveValue(
    "2025/01/16",
  );
});

describe("datetime search in the browser timezone", { timeout: 30_000 }, () => {
  test.each(filters)("$label searches and reopens the displayed second", ({
    index,
    key,
    instant,
    stored,
  }) => {
    render(
      <AttributeValue
        attrInfo={{
          type: EntryAttributeTypeTypeEnum.DATETIME,
          value: { asString: stored },
        }}
      />,
      { wrapper: TestWrapper },
    );
    const displayed = screen.getByText(localText(instant));
    expect(displayed).toBeVisible();
    const { onSelect, unmount } = openMenu();
    const input = screen.getAllByRole("textbox")[index];
    fireEvent.change(input, { target: { value: displayed.textContent } });
    fireEvent.click(
      screen.getAllByRole("button", { name: /Choose date/ })[index],
    );
    fireEvent.click(screen.getByRole("button", { name: "OK" }));
    expect(onSelect).toHaveBeenCalledExactlyOnceWith({
      attrFilter: { filterKey: key, keyword: instant },
    });
    unmount();
    openMenu(onSelect.mock.calls[0][0].attrFilter);
    expect(screen.getAllByRole("textbox")[index]).toHaveValue(
      localText(instant),
    );
  });

  test("validates a reopened range at the precision shown in its fields", () => {
    const { onSelect } = openMenu({
      filterKey: FilterKey.TEXT_CONTAINED,
      keyword: "2025-01-15T23:15:27.999Z~2025-01-15T23:15:27.123Z",
    });
    const start = screen.getAllByRole("textbox", { name: "開始日時" })[0];
    const end = screen.getAllByRole("textbox", { name: "終了日時" })[0];
    const rangeError = "終了日時は開始日時以降を指定してください";
    expect(start).toHaveValue(localText(winter));
    expect(end).toHaveValue(localText(winter));
    expect(screen.queryAllByText(rangeError)).toHaveLength(0);

    fireEvent.change(start, {
      target: { value: localText("2025-01-15T23:15:28.000Z") },
    });
    expect(screen.getByText(rangeError)).toBeVisible();
    const apply = screen.getByRole("button", { name: "適用" });
    expect(apply).toBeDisabled();
    fireEvent.click(apply);
    expect(onSelect).not.toHaveBeenCalled();
  });

  test.each(filters)("$label submits and reopens a winter-to-summer range", ({
    index,
    key,
  }) => {
    const { onSelect, unmount } = openMenu();
    fireEvent.click(screen.getByRole("checkbox"));
    fireEvent.change(
      screen.getAllByRole("textbox", { name: "開始日時" })[index],
      {
        target: { value: localText(winter) },
      },
    );
    fireEvent.change(
      screen.getAllByRole("textbox", { name: "終了日時" })[index],
      {
        target: { value: localText(summer) },
      },
    );
    fireEvent.click(screen.getByRole("button", { name: "適用" }));
    expect(onSelect).toHaveBeenCalledExactlyOnceWith({
      attrFilter: { filterKey: key, keyword: winter + "~" + summer },
    });
    unmount();
    openMenu(onSelect.mock.calls[0][0].attrFilter);
    expect(
      screen.getAllByRole("textbox", { name: "開始日時" })[index],
    ).toHaveValue(localText(winter));
    expect(
      screen.getAllByRole("textbox", { name: "終了日時" })[index],
    ).toHaveValue(localText(summer));
  });
});

describe(
  "datetime entry save and display in the browser timezone",
  { timeout: 30_000 },
  () => {
    const attr = {
      id: 17,
      index: 0,
      name: "Timestamp",
      type: EntryAttributeTypeTypeEnum.DATETIME,
      is_writable: true,
      is_mandatory: true,
    };
    const server = setupServer(
      http.get("http://localhost/entity/api/v2/2/", () =>
        HttpResponse.json({
          id: 2,
          name: "Events",
          item_name_type: "US",
          attrs: [attr],
          webhooks: [],
          isolation_rules: [],
          delete_chain_exclude_entities: [],
        }),
      ),
    );
    beforeAll(() => server.listen({ onUnhandledRequest: "error" }));
    afterEach(() => server.resetHandlers());
    afterAll(() => server.close());

    test.each([
      winter,
      summer,
    ])("saves %s and displays it in local time", async (instant) => {
      const submitted = vi.fn();
      server.use(
        http.post(
          "http://localhost/entity/api/v2/2/entries/",
          async ({ request }) => {
            submitted(await request.json());
            return new HttpResponse(null, { status: 201 });
          },
        ),
      );
      const router = createMemoryRouter(
        [
          { path: newEntryPath(":entityId"), element: <EntryEditPage /> },
          { path: entityEntriesPath(":entityId"), element: <div /> },
        ],
        { initialEntries: [newEntryPath(2)] },
      );
      render(<RouterProvider router={router} />, {
        wrapper: TestWrapperWithoutRoutes,
      });
      fireEvent.change(
        await screen.findByRole("textbox", { name: "アイテム名" }),
        {
          target: { value: "event" },
        },
      );
      fireEvent.change(screen.getByRole("textbox", { name: "" }), {
        target: { value: localText(instant) },
      });
      const save = screen.getByRole("button", { name: "保存" });
      await waitFor(() => expect(save).toBeEnabled());
      fireEvent.click(save);
      await waitFor(() =>
        expect(submitted).toHaveBeenCalledExactlyOnceWith({
          name: "event",
          attrs: [{ id: attr.id, value: instant }],
        }),
      );
      render(
        <AttributeValue
          attrInfo={{
            type: attr.type,
            value: { asString: submitted.mock.calls[0][0].attrs[0].value },
          }}
        />,
        { wrapper: TestWrapper },
      );
      expect(screen.getByText(localText(instant))).toBeVisible();
    });
  },
);

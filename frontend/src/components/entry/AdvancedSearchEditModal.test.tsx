import {
  act,
  fireEvent,
  render,
  screen,
  waitFor,
} from "@testing-library/react";

import { AdvancedSearchEditModal } from "./AdvancedSearchEditModal";

import { TestWrapper } from "TestWrapper";
import {
  AdvancedSearchResultAttrInfoFilterKeyEnum,
  EntryAttributeTypeTypeEnum,
} from "apiclient/autogenerated";
import i18n from "i18n/config";
import { aironeApiClient } from "repository/AironeApiClient";

vi.mock("hooks/usePagodaSWR", () => ({
  usePagodaSWR: () => ({ data: ["attrA", "attrB", "attrC"] }),
}));
vi.mock("react-router", async () => ({
  ...((await vi.importActual("react-router")) as object),
  useNavigate: () => vi.fn(),
}));

describe("AdvancedSearchEditModal", () => {
  const joinedBulkProps = {
    openModal: true,
    handleClose: () => {},
    modelIds: [1, 2, 3],
    attrsFilter: {
      attrA: {
        filterKey: AdvancedSearchResultAttrInfoFilterKeyEnum.CLEARED,
        keyword: "",
      },
      refs: {
        filterKey: AdvancedSearchResultAttrInfoFilterKeyEnum.CLEARED,
        keyword: "",
      },
      "refs.status": {
        baseAttrname: "refs",
        joinedAttrname: "status",
        filterKey: AdvancedSearchResultAttrInfoFilterKeyEnum.TEXT_CONTAINED,
        keyword: "active",
      },
    },
    joinAttrs: [{ name: "refs", attrinfo: [{ name: "status" }] }],
    targetAttrID: 10,
    targetAttrname: "attrA",
    targetAttrtype: EntryAttributeTypeTypeEnum.STRING,
    matchedCount: 5000,
  };
  const baseFilters = [
    {
      name: "attrA",
      filterKey: AdvancedSearchResultAttrInfoFilterKeyEnum.CLEARED,
      keyword: "",
    },
    {
      name: "refs",
      filterKey: AdvancedSearchResultAttrInfoFilterKeyEnum.CLEARED,
      keyword: "",
    },
  ];
  const joinedResult = (ids: number[]) => ({
    count: ids.length,
    totalCount: 5000,
    values: ids.map((id) => ({
      entry: { id, name: `対象${id}` },
      entity: { id: id > 1000 ? 2 : 1, name: "モデル" },
      attrs: {},
      isReadable: true,
      referrals: [],
    })),
  });
  const mockJoinedBulkDependencies = () => {
    vi.spyOn(aironeApiClient, "getEntryReferral").mockResolvedValue({
      count: 0,
      results: [],
    });
    vi.spyOn(aironeApiClient, "getEntityAttrs").mockImplementation(
      async ([modelId]) => [
        {
          id: modelId === 2 ? 20 : 10,
          name: "attrA",
          type: EntryAttributeTypeTypeEnum.STRING,
        },
      ],
    );
    return vi.spyOn(aironeApiClient, "bulkUpdateEntries").mockResolvedValue();
  };

  test("resolves all joined matches across pages and updates only their IDs per model", async () => {
    await act(async () => {
      await i18n.changeLanguage("ja");
    });
    const update = mockJoinedBulkDependencies();
    const firstPageIds = Array.from({ length: 1000 }, (_, index) => index + 1);
    const search = vi
      .spyOn(aironeApiClient, "advancedSearch")
      .mockImplementation(
        async (_models, _attrs, _joins, _hasReferral, _referral, _all, page) =>
          joinedResult(page === 1 ? firstPageIds : [1, 1001]),
      );
    try {
      render(
        <AdvancedSearchEditModal {...joinedBulkProps} matchedCount={0} />,
        {
          wrapper: TestWrapper,
        },
      );
      await screen.findByText(
        "チェックがないため、検索条件に一致する全1001件が変更対象です。",
      );
      expect(search).toHaveBeenCalledWith(
        [1, 2, 3],
        baseFilters,
        [
          {
            name: "refs",
            attrinfo: [
              {
                name: "status",
                filterKey:
                  AdvancedSearchResultAttrInfoFilterKeyEnum.TEXT_CONTAINED,
                keyword: "active",
              },
            ],
          },
        ],
        false,
        "",
        false,
        2,
        1000,
        0,
        undefined,
        [],
        [],
      );
      fireEvent.click(
        screen.getByRole("button", {
          name: "更新対象のアイテムと依存関係（1001件）",
        }),
      );
      await screen.findByText("対象1");
      fireEvent.click(screen.getByRole("button", { name: "Go to page 2" }));
      await screen.findByText("対象11");
      fireEvent.change(screen.getByRole("textbox"), {
        target: { value: "changed" },
      });
      await waitFor(() =>
        expect(screen.getByRole("button", { name: "更新" })).toBeEnabled(),
      );
      fireEvent.click(screen.getByRole("button", { name: "更新" }));
      await waitFor(() => expect(update).toHaveBeenCalledTimes(2));
      expect(update).toHaveBeenCalledWith(
        1,
        { id: 10, value: "changed" },
        baseFilters,
        "",
        undefined,
        firstPageIds,
      );
      expect(update).toHaveBeenCalledWith(
        2,
        { id: 20, value: "changed" },
        baseFilters,
        "",
        undefined,
        [1001],
      );
    } finally {
      vi.restoreAllMocks();
    }
  });

  test.each([
    "empty",
    "failure",
  ])("prevents a joined bulk update when target resolution returns %s", async (mode) => {
    await act(async () => {
      await i18n.changeLanguage("ja");
    });
    const update = mockJoinedBulkDependencies();
    vi.spyOn(aironeApiClient, "advancedSearch").mockImplementation(
      async (_models, _attrs, _joins, _hasReferral, _referral, _all, page) => {
        if (mode === "empty") return joinedResult([]);
        if (page === 1)
          return joinedResult(
            Array.from({ length: 1000 }, (_, index) => index + 1),
          );
        throw new Error("Second page failed");
      },
    );
    try {
      render(<AdvancedSearchEditModal {...joinedBulkProps} />, {
        wrapper: TestWrapper,
      });
      if (mode === "empty") {
        await screen.findByText(i18n.t("advancedSearch.editModal.noTargets"));
      } else {
        await screen.findByText(
          i18n.t("advancedSearch.editModal.previewFailed"),
        );
      }
      expect(screen.getByRole("button", { name: "更新" })).toBeDisabled();
      fireEvent.click(screen.getByRole("button", { name: "更新" }));
      expect(update).not.toHaveBeenCalled();
    } finally {
      vi.restoreAllMocks();
    }
  });

  test("keeps explicit selection when joined filters are present", async () => {
    await act(async () => {
      await i18n.changeLanguage("ja");
    });
    const update = mockJoinedBulkDependencies();
    const search = vi.spyOn(aironeApiClient, "advancedSearch");
    try {
      render(
        <AdvancedSearchEditModal
          {...joinedBulkProps}
          selectedEntries={[{ id: 5, name: "選択アイテム", modelId: 1 }]}
        />,
        { wrapper: TestWrapper },
      );
      fireEvent.change(screen.getByRole("textbox"), {
        target: { value: "changed" },
      });
      await waitFor(() =>
        expect(screen.getByRole("button", { name: "更新" })).toBeEnabled(),
      );
      fireEvent.click(screen.getByRole("button", { name: "更新" }));
      await waitFor(() =>
        expect(update).toHaveBeenCalledWith(
          1,
          { id: 10, value: "changed" },
          baseFilters,
          "",
          undefined,
          [5],
        ),
      );
      expect(search).not.toHaveBeenCalled();
    } finally {
      vi.restoreAllMocks();
    }
  });

  test.each([
    [EntryAttributeTypeTypeEnum.OBJECT, null],
    [EntryAttributeTypeTypeEnum.ARRAY_OBJECT, []],
  ])("submits an empty value for untouched object type %s", async (type, emptyValue) => {
    await act(async () => {
      await i18n.changeLanguage("ja");
    });
    const referral = vi
      .spyOn(aironeApiClient, "getEntryReferral")
      .mockResolvedValue({ count: 0, results: [] });
    const attrs = vi
      .spyOn(aironeApiClient, "getEntityAttrs")
      .mockResolvedValue([{ id: 10, name: "attrA", type }]);
    const update = vi
      .spyOn(aironeApiClient, "bulkUpdateEntries")
      .mockResolvedValue();
    try {
      render(
        <AdvancedSearchEditModal
          openModal={true}
          handleClose={() => {}}
          modelIds={[1]}
          attrsFilter={{}}
          targetAttrID={10}
          targetAttrname="attrA"
          targetAttrtype={type}
          selectedEntries={[{ id: 5, name: "更新アイテム", modelId: 1 }]}
        />,
        { wrapper: TestWrapper },
      );
      await waitFor(() =>
        expect(screen.getByRole("button", { name: "更新" })).toBeEnabled(),
      );
      fireEvent.click(screen.getByRole("button", { name: "更新" }));
      await waitFor(() =>
        expect(update).toHaveBeenCalledWith(
          1,
          { id: 10, value: emptyValue },
          [],
          "",
          undefined,
          [5],
        ),
      );
    } finally {
      referral.mockRestore();
      attrs.mockRestore();
      update.mockRestore();
    }
  });

  test("submits an array attribute for selected items", async () => {
    await act(async () => {
      await i18n.changeLanguage("ja");
    });
    const referral = vi
      .spyOn(aironeApiClient, "getEntryReferral")
      .mockResolvedValue({ count: 0, results: [] });
    const attrs = vi
      .spyOn(aironeApiClient, "getEntityAttrs")
      .mockResolvedValue([
        {
          id: 10,
          name: "attrA",
          type: EntryAttributeTypeTypeEnum.ARRAY_STRING,
        },
      ]);
    const update = vi
      .spyOn(aironeApiClient, "bulkUpdateEntries")
      .mockResolvedValue();
    render(
      <AdvancedSearchEditModal
        openModal={true}
        handleClose={() => {}}
        modelIds={[1]}
        attrsFilter={{}}
        targetAttrID={10}
        targetAttrname="attrA"
        targetAttrtype={EntryAttributeTypeTypeEnum.ARRAY_STRING}
        selectedEntries={[{ id: 5, name: "更新アイテム", modelId: 1 }]}
      />,
      { wrapper: TestWrapper },
    );
    await waitFor(() =>
      expect(screen.getByRole("button", { name: "更新" })).toBeEnabled(),
    );
    fireEvent.change(screen.getByRole("textbox"), {
      target: { value: "new value" },
    });
    fireEvent.click(screen.getByRole("button", { name: "更新" }));
    await waitFor(() =>
      expect(update).toHaveBeenCalledWith(
        1,
        { id: 10, value: ["new value"] },
        [],
        "",
        undefined,
        [5],
      ),
    );
    referral.mockRestore();
    attrs.mockRestore();
    update.mockRestore();
  });

  test("updates every matching item when no checkbox is selected", async () => {
    await act(async () => {
      await i18n.changeLanguage("ja");
    });
    const search = vi
      .spyOn(aironeApiClient, "advancedSearch")
      .mockImplementation(
        async (_models, _attrs, _joins, _hasReferral, _referral, _all, page) =>
          ({
            count: 10,
            totalCount: 25,
            values: Array.from({ length: 10 }, (_, index) => ({
              entry: {
                id: (page - 1) * 10 + index + 1,
                name: `対象${(page - 1) * 10 + index + 1}`,
              },
              entity: { id: 1, name: "モデル" },
              attrs: {},
            })),
          }) as Awaited<ReturnType<typeof aironeApiClient.advancedSearch>>,
      );
    const referral = vi
      .spyOn(aironeApiClient, "getEntryReferral")
      .mockResolvedValue({ count: 0, results: [] });
    const attrs = vi
      .spyOn(aironeApiClient, "getEntityAttrs")
      .mockResolvedValue([
        {
          id: 10,
          name: "attrA",
          type: EntryAttributeTypeTypeEnum.STRING,
        },
      ]);
    const update = vi
      .spyOn(aironeApiClient, "bulkUpdateEntries")
      .mockResolvedValue();
    render(
      <AdvancedSearchEditModal
        openModal={true}
        handleClose={() => {}}
        modelIds={[1]}
        attrsFilter={{}}
        targetAttrID={10}
        targetAttrname="attrA"
        targetAttrtype={EntryAttributeTypeTypeEnum.STRING}
        matchedCount={25}
      />,
      { wrapper: TestWrapper },
    );
    expect(
      await screen.findByText(
        "チェックがないため、検索条件に一致する全25件が変更対象です。",
      ),
    ).toBeInTheDocument();
    fireEvent.click(
      screen.getByRole("button", {
        name: "更新対象のアイテムと依存関係（25件）",
      }),
    );
    await screen.findByText("対象1");
    fireEvent.click(screen.getByRole("button", { name: "Go to page 2" }));
    await screen.findByText("対象11");
    expect(search).toHaveBeenCalledWith(
      [1],
      [],
      [],
      false,
      "",
      false,
      2,
      10,
      0,
      undefined,
    );
    fireEvent.change(screen.getByRole("textbox"), {
      target: { value: "changed" },
    });
    await waitFor(() =>
      expect(screen.getByRole("button", { name: "更新" })).toBeEnabled(),
    );
    fireEvent.click(screen.getByRole("button", { name: "更新" }));
    await waitFor(() =>
      expect(update).toHaveBeenCalledWith(
        1,
        expect.anything(),
        [],
        "",
        undefined,
        undefined,
      ),
    );
    search.mockRestore();
    referral.mockRestore();
    attrs.mockRestore();
    update.mockRestore();
  });
  test("shows selected item names and their references before update", async () => {
    await act(async () => {
      await i18n.changeLanguage("ja");
    });
    const referral = vi
      .spyOn(aironeApiClient, "getEntryReferral")
      .mockResolvedValue({
        count: 1,
        results: [
          {
            id: 20,
            name: "依存アイテム",
            schema: { id: 3, name: "参照モデル", permission: 1 },
            isActive: true,
            deletedUser: null,
            updatedTime: new Date(0),
            aliases: [],
            permission: 1,
          },
        ],
      });
    render(
      <AdvancedSearchEditModal
        openModal={true}
        handleClose={() => {}}
        modelIds={[1]}
        attrsFilter={{}}
        targetAttrID={10}
        targetAttrname="attrA"
        targetAttrtype={EntryAttributeTypeTypeEnum.STRING}
        selectedEntries={[{ id: 5, name: "更新アイテム", modelId: 1 }]}
      />,
      { wrapper: TestWrapper },
    );
    const targetSummary = screen.getByRole("button", {
      name: "更新対象のアイテムと依存関係（1件）",
    });
    expect(targetSummary).toHaveAttribute("aria-expanded", "false");
    fireEvent.click(targetSummary);
    expect(screen.getByText("更新アイテム")).toBeInTheDocument();
    fireEvent.click(await screen.findByRole("button", { name: "参照元: 1件" }));
    expect(
      await screen.findByRole("link", { name: "参照モデル / 依存アイテム" }),
    ).toBeInTheDocument();
    expect(referral).toHaveBeenCalledWith(5, 1);
    referral.mockRestore();
  });

  test("shows large target lists ten at a time", async () => {
    await act(async () => {
      await i18n.changeLanguage("ja");
    });
    const referral = vi
      .spyOn(aironeApiClient, "getEntryReferral")
      .mockResolvedValue({ count: 0, results: [] });
    render(
      <AdvancedSearchEditModal
        openModal={true}
        handleClose={() => {}}
        modelIds={[1]}
        attrsFilter={{}}
        targetAttrID={10}
        targetAttrname="attrA"
        targetAttrtype={EntryAttributeTypeTypeEnum.STRING}
        selectedEntries={Array.from({ length: 11 }, (_, index) => ({
          id: index + 1,
          name: `対象${index + 1}`,
          modelId: 1,
        }))}
      />,
      { wrapper: TestWrapper },
    );
    fireEvent.click(
      screen.getByRole("button", {
        name: "更新対象のアイテムと依存関係（11件）",
      }),
    );
    expect(screen.getByText("対象1")).toBeInTheDocument();
    expect(screen.queryByText("対象11")).not.toBeInTheDocument();
    fireEvent.click(screen.getByRole("button", { name: "Go to page 2" }));
    expect(screen.getByText("対象11")).toBeInTheDocument();
    expect(screen.queryByText("対象1")).not.toBeInTheDocument();
    referral.mockRestore();
  });
  test("should render modal with title and buttons", () => {
    render(
      <AdvancedSearchEditModal
        openModal={true}
        handleClose={() => {}}
        modelIds={[1]}
        attrsFilter={{}}
        targetAttrID={10}
        targetAttrname={"attrA"}
        targetAttrtype={EntryAttributeTypeTypeEnum.STRING}
      />,
      { wrapper: TestWrapper },
    );
    expect(
      screen.getByText("一括更新する（変更後の）値に更新"),
    ).toBeInTheDocument();
    expect(screen.getByText("属性「attrA」の変更後の値")).toBeInTheDocument();
    expect(screen.getByText("更新")).toBeInTheDocument();
    expect(screen.getByText("キャンセル")).toBeInTheDocument();
  });

  test("renders in English", async () => {
    await act(async () => {
      await i18n.changeLanguage("en");
    });
    render(
      <AdvancedSearchEditModal
        openModal={true}
        handleClose={() => {}}
        modelIds={[1]}
        attrsFilter={{}}
        targetAttrID={10}
        targetAttrname={"attrA"}
        targetAttrtype={EntryAttributeTypeTypeEnum.STRING}
      />,
      { wrapper: TestWrapper },
    );
    expect(
      screen.getByText("Update to the (changed) value for bulk update"),
    ).toBeInTheDocument();
    expect(
      screen.getByText('New value for attribute "attrA"'),
    ).toBeInTheDocument();
    expect(screen.getByText("Update")).toBeInTheDocument();
    expect(screen.getByText("Cancel")).toBeInTheDocument();
  });
});

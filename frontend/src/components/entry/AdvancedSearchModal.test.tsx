/**
 */
import { act, render, screen, fireEvent, within } from "@testing-library/react";

import { AdvancedSearchModal } from "./AdvancedSearchModal";

import { TestWrapper } from "TestWrapper";
import {
  AdvancedSearchResultAttrInfo,
  AdvancedSearchResultAttrInfoFilterKeyEnum,
  AdvancedSearchJoinAttrInfo,
} from "apiclient/autogenerated";
import i18n from "i18n/config";
import { getAdvancedSearchColumnOrderKey } from "services/entry/AdvancedSearchColumnOrder";

const navigateMock = vi.hoisted(() => vi.fn());

vi.mock("react-router", async () => ({
  ...((await vi.importActual("react-router")) as object),
  useNavigate: () => navigateMock,
}));

describe("AdvancedSearchModal", () => {
  const attrNames = ["attrA", "attrB", "attrC"];
  const initialAttrNames = ["attrA", "attrC"];
  const attrInfos: AdvancedSearchResultAttrInfo[] = [
    {
      name: "attrA",
      filterKey: AdvancedSearchResultAttrInfoFilterKeyEnum.CLEARED,
      keyword: "",
    },
    {
      name: "attrB",
      filterKey: AdvancedSearchResultAttrInfoFilterKeyEnum.CLEARED,
      keyword: "",
    },
    {
      name: "attrC",
      filterKey: AdvancedSearchResultAttrInfoFilterKeyEnum.CLEARED,
      keyword: "",
    },
  ];
  const joinAttrs: AdvancedSearchJoinAttrInfo[] = [];

  afterEach(() => {
    window.history.replaceState(null, "", "/");
    localStorage.clear();
    navigateMock.mockClear();
  });

  test("discards unsaved changes when reopened with the current search", () => {
    const props = {
      openModal: true,
      setOpenModal: vi.fn(),
      attrNames,
      initialAttrNames,
      attrInfos,
      joinAttrs,
    };
    const { rerender } = render(<AdvancedSearchModal {...props} />, {
      wrapper: TestWrapper,
    });

    fireEvent.click(screen.getByLabelText("Clear"));
    fireEvent.click(screen.getByRole("checkbox"));
    expect(screen.queryByText("attrA")).not.toBeInTheDocument();
    expect(screen.getByRole("checkbox")).toBeChecked();

    fireEvent.click(screen.getByText("キャンセル"));
    rerender(<AdvancedSearchModal {...props} openModal={false} />);
    window.history.replaceState(null, "", "/?has_referral=true");
    rerender(<AdvancedSearchModal {...props} initialAttrNames={["attrB"]} />);

    expect(screen.queryByText("attrA")).not.toBeInTheDocument();
    expect(screen.getAllByText("attrB")[0]).toBeInTheDocument();
    expect(screen.queryByText("attrC")).not.toBeInTheDocument();
    expect(screen.getByRole("checkbox")).toBeChecked();

    fireEvent.click(screen.getByRole("checkbox"));
    rerender(
      <AdvancedSearchModal
        {...props}
        openModal={false}
        initialAttrNames={["attrB"]}
      />,
    );
    rerender(<AdvancedSearchModal {...props} initialAttrNames={["attrB"]} />);
    expect(screen.getByRole("checkbox")).toBeChecked();
  });

  test("preserves edits for equivalent props and resets when search changes", () => {
    const props = {
      openModal: true,
      setOpenModal: vi.fn(),
      attrNames,
      initialAttrNames,
      attrInfos,
      joinAttrs,
    };
    const { rerender } = render(<AdvancedSearchModal {...props} />, {
      wrapper: TestWrapper,
    });

    fireEvent.click(screen.getByLabelText("Clear"));
    fireEvent.click(screen.getByRole("checkbox"));
    rerender(
      <AdvancedSearchModal
        {...props}
        initialAttrNames={[...initialAttrNames]}
      />,
    );
    expect(screen.queryByText("attrA")).not.toBeInTheDocument();
    expect(screen.queryByText("attrC")).not.toBeInTheDocument();
    expect(screen.getByRole("checkbox")).toBeChecked();

    rerender(<AdvancedSearchModal {...props} initialAttrNames={["attrB"]} />);
    expect(screen.getAllByText("attrB")[0]).toBeInTheDocument();
    expect(screen.getByRole("checkbox")).not.toBeChecked();

    window.history.replaceState(null, "", "/?has_referral=true");
    rerender(<AdvancedSearchModal {...props} initialAttrNames={["attrB"]} />);
    expect(screen.getAllByText("attrB")[0]).toBeInTheDocument();
    expect(screen.getByRole("checkbox")).toBeChecked();

    rerender(<AdvancedSearchModal {...props} initialAttrNames={[]} />);
    expect(screen.queryByText("attrB")).not.toBeInTheDocument();
  });

  test("should render modal with title, buttons, and checkbox", () => {
    render(
      <AdvancedSearchModal
        openModal={true}
        setOpenModal={vi.fn()}
        attrNames={attrNames}
        initialAttrNames={initialAttrNames}
        attrInfos={attrInfos}
        joinAttrs={joinAttrs}
      />,
      { wrapper: TestWrapper },
    );
    expect(screen.getByText("検索属性の再設定")).toBeInTheDocument();
    expect(screen.getByText("保存")).toBeInTheDocument();
    expect(screen.getByText("キャンセル")).toBeInTheDocument();
    expect(screen.getByText("参照アイテムも含める")).toBeInTheDocument();
    expect(screen.getByRole("checkbox")).toBeInTheDocument();
  });

  test("should call setOpenModal(false) when clicking cancel button", () => {
    const setOpenModal = vi.fn();
    render(
      <AdvancedSearchModal
        openModal={true}
        setOpenModal={setOpenModal}
        attrNames={attrNames}
        initialAttrNames={initialAttrNames}
        attrInfos={attrInfos}
        joinAttrs={joinAttrs}
      />,
      { wrapper: TestWrapper },
    );
    fireEvent.click(screen.getByText("キャンセル"));
    expect(setOpenModal).toHaveBeenCalledWith(false);
  });

  test("selects every available attribute from the reset modal", async () => {
    render(
      <AdvancedSearchModal
        openModal={true}
        setOpenModal={vi.fn()}
        attrNames={attrNames}
        initialAttrNames={initialAttrNames}
        attrInfos={attrInfos}
        joinAttrs={joinAttrs}
      />,
      { wrapper: TestWrapper },
    );

    fireEvent.click(screen.getByRole("button", { name: "Open" }));
    fireEvent.click(await screen.findByText("すべて選択"));

    expect(screen.getAllByText("attrA")[0]).toBeInTheDocument();
    expect(screen.getAllByText("attrB")[0]).toBeInTheDocument();
    expect(screen.getAllByText("attrC")[0]).toBeInTheDocument();
  });

  test("saves the selected attribute order as the result column order", () => {
    const columnOrderKey = getAdvancedSearchColumnOrderKey([100], false);
    localStorage.setItem(
      columnOrderKey,
      JSON.stringify(["attrA", "__entry_name__", "attrC", "attrC.child"]),
    );
    render(
      <AdvancedSearchModal
        openModal
        setOpenModal={vi.fn()}
        attrNames={attrNames}
        initialAttrNames={initialAttrNames}
        attrInfos={attrInfos}
        joinAttrs={[{ name: "attrC", attrinfo: [{ name: "child" }] }]}
        entityIds={[100]}
      />,
      { wrapper: TestWrapper },
    );
    const selectedList = screen.getByRole("list", {
      name: "列の順番（ドラッグして変更）",
    });
    const selectedOrder = () =>
      Array.from(selectedList.children, (item) =>
        item.getAttribute("data-selected-attribute"),
      );
    expect(selectedOrder()).toEqual(["attrA", "__entry_name__", "attrC"]);
    expect(within(selectedList).getByText("アイテム名")).toBeInTheDocument();
    const dataTransfer = {
      effectAllowed: "none",
      dropEffect: "none",
      setData: vi.fn(),
    };
    fireEvent.dragStart(
      within(selectedList).getByRole("button", {
        name: "attrC列をドラッグして移動",
      }),
      { dataTransfer },
    );
    const target = selectedList.querySelector(
      '[data-selected-attribute="attrA"]',
    )!;
    fireEvent.dragOver(target, { dataTransfer });
    fireEvent.drop(target, { dataTransfer });
    expect(selectedOrder()).toEqual(["attrC", "attrA", "__entry_name__"]);

    fireEvent.click(screen.getByRole("button", { name: "保存" }));
    expect(JSON.parse(localStorage.getItem(columnOrderKey) ?? "[]")).toEqual([
      "attrC",
      "attrC.child",
      "attrA",
      "__entry_name__",
    ]);
    const navigation = navigateMock.mock.calls[0]?.[0];
    const params = new URLSearchParams(navigation.search);
    expect(
      JSON.parse(params.get("attrinfo") ?? "[]").map(
        (attr: { name: string }) => attr.name,
      ),
    ).toEqual(["attrC", "attrA"]);
  });

  test("moves the item name within the reset modal and saves its position", () => {
    const columnOrderKey = getAdvancedSearchColumnOrderKey([100], false);
    localStorage.setItem(
      columnOrderKey,
      JSON.stringify(["attrA", "__entry_name__", "attrC"]),
    );
    render(
      <AdvancedSearchModal
        openModal
        setOpenModal={vi.fn()}
        attrNames={attrNames}
        initialAttrNames={initialAttrNames}
        attrInfos={attrInfos}
        joinAttrs={joinAttrs}
        entityIds={[100]}
      />,
      { wrapper: TestWrapper },
    );
    const list = screen.getByRole("list", {
      name: "列の順番（ドラッグして変更）",
    });
    const dataTransfer = {
      effectAllowed: "none",
      dropEffect: "none",
      setData: vi.fn(),
    };
    fireEvent.dragStart(
      within(list).getByRole("button", {
        name: "アイテム名列をドラッグして移動",
      }),
      { dataTransfer },
    );
    const target = list.querySelector('[data-selected-attribute="attrC"]')!;
    fireEvent.dragOver(target, { dataTransfer });
    fireEvent.drop(target, { dataTransfer });
    expect(
      Array.from(list.children, (item) =>
        item.getAttribute("data-selected-attribute"),
      ),
    ).toEqual(["attrA", "attrC", "__entry_name__"]);

    fireEvent.click(screen.getByRole("button", { name: "保存" }));
    expect(JSON.parse(localStorage.getItem(columnOrderKey) ?? "[]")).toEqual([
      "attrA",
      "attrC",
      "__entry_name__",
    ]);
  });

  test("renders in English", async () => {
    await act(async () => {
      await i18n.changeLanguage("en");
    });
    render(
      <AdvancedSearchModal
        openModal={true}
        setOpenModal={vi.fn()}
        attrNames={attrNames}
        initialAttrNames={initialAttrNames}
        attrInfos={attrInfos}
        joinAttrs={joinAttrs}
      />,
      { wrapper: TestWrapper },
    );
    expect(screen.getByText("Reset search attributes")).toBeInTheDocument();
    expect(screen.getByText("Save")).toBeInTheDocument();
    expect(screen.getByText("Cancel")).toBeInTheDocument();
    expect(screen.getByText("Include referral entries")).toBeInTheDocument();
  });

  test("should not render modal when openModal is false", () => {
    render(
      <AdvancedSearchModal
        openModal={false}
        setOpenModal={vi.fn()}
        attrNames={attrNames}
        initialAttrNames={initialAttrNames}
        attrInfos={attrInfos}
        joinAttrs={joinAttrs}
      />,
      { wrapper: TestWrapper },
    );
    expect(screen.queryByRole("dialog")).toBeNull();
  });
});

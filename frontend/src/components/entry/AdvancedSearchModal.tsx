import DragIndicatorIcon from "@mui/icons-material/DragIndicator";
import {
  Box,
  Button,
  Checkbox,
  IconButton,
  List,
  ListItem,
  ListItemText,
  TextField,
  Typography,
} from "@mui/material";
import { Dispatch, FC, SetStateAction, useState } from "react";
import { useNavigate } from "react-router";

import { useTranslation } from "../../hooks/useTranslation";
import { formatAdvancedSearchParams } from "../../services/entry/AdvancedSearch";
import { AironeModal } from "../common/AironeModal";
import { AutocompleteWithAllSelector } from "../common/AutocompleteWithAllSelector";

import {
  AdvancedSearchJoinAttrInfo,
  AdvancedSearchResultAttrInfo,
  AdvancedSearchResultAttrInfoFilterKeyEnum,
} from "apiclient/autogenerated";
import { ENTRY_NAME_SORT_TARGET } from "services/entry/AdvancedSearch";
import {
  getAdvancedSearchColumnOrderKey,
  keepEntryNamePosition,
  orderSelectedAttributes,
  readAdvancedSearchColumnOrder,
  writeAdvancedSearchColumnOrder,
} from "services/entry/AdvancedSearchColumnOrder";

interface Props {
  openModal: boolean;
  setOpenModal: Dispatch<SetStateAction<boolean>>;
  attrNames: string[];
  initialAttrNames: string[];
  attrInfos: AdvancedSearchResultAttrInfo[];
  joinAttrs: AdvancedSearchJoinAttrInfo[];
  entityIds?: number[];
  searchAllEntities?: boolean;
}

export const AdvancedSearchModal: FC<Props> = (props) => {
  const initialHasReferral =
    new URLSearchParams(location.search).get("has_referral") === "true";

  return props.openModal ? (
    <AdvancedSearchModalForm
      {...props}
      key={JSON.stringify([
        props.initialAttrNames,
        initialHasReferral,
        props.entityIds,
        props.searchAllEntities,
      ])}
      initialHasReferral={initialHasReferral}
    />
  ) : null;
};

const AdvancedSearchModalForm: FC<Props & { initialHasReferral: boolean }> = ({
  openModal,
  setOpenModal,
  attrNames,
  initialAttrNames,
  attrInfos,
  joinAttrs,
  initialHasReferral,
  entityIds = [],
  searchAllEntities = false,
}) => {
  const navigate = useNavigate();
  const { t } = useTranslation();
  const columnOrderKey = getAdvancedSearchColumnOrderKey(
    entityIds,
    searchAllEntities,
  );
  const [orderedColumns, setOrderedColumns] = useState(() => {
    const savedColumns = readAdvancedSearchColumnOrder(columnOrderKey);
    return keepEntryNamePosition(
      orderSelectedAttributes(initialAttrNames, savedColumns).map((name) => [
        name,
      ]),
      savedColumns,
    );
  });
  const selectedAttrNames = orderedColumns.filter(
    (name) => name !== ENTRY_NAME_SORT_TARGET,
  );
  const [hasReferral, setHasReferral] = useState(initialHasReferral);
  const [draggedAttrName, setDraggedAttrName] = useState<string | null>(null);
  const [dropTargetAttrName, setDropTargetAttrName] = useState<string | null>(
    null,
  );

  const reorderColumns = (source: string, target: string) => {
    const from = orderedColumns.indexOf(source);
    const to = orderedColumns.indexOf(target);
    if (from < 0 || to < 0 || from === to) return;
    const next = [...orderedColumns];
    next.splice(from, 1);
    next.splice(to, 0, source);
    setOrderedColumns(next);
  };

  const handleUpdatePageURL = () => {
    const attributeGroups = selectedAttrNames.map((name) => [
      name,
      ...joinAttrs
        .filter((join) => join.name === name)
        .flatMap((join) => join.attrinfo.map((info) => `${name}.${info.name}`)),
    ]);
    writeAdvancedSearchColumnOrder(
      columnOrderKey,
      keepEntryNamePosition(attributeGroups, orderedColumns),
    );
    const params = formatAdvancedSearchParams({
      attrsFilter: Object.fromEntries(
        selectedAttrNames.map((attrName) => {
          const attrInfo = attrInfos.find((info) => info.name === attrName);
          return [
            attrName,
            {
              filterKey:
                attrInfo?.filterKey ??
                AdvancedSearchResultAttrInfoFilterKeyEnum.CLEARED,
              keyword: attrInfo?.keyword ?? "",
            },
          ];
        }),
      ),
      hasReferral,
      baseParams: new URLSearchParams(location.search),
      joinAttrs: joinAttrs.filter((joinAttr) =>
        selectedAttrNames.includes(joinAttr.name),
      ),
    });

    // Update Page URL parameters
    navigate({
      pathname: location.pathname,
      search: "?" + params.toString(),
    });
    navigate(0);
  };

  return (
    <AironeModal
      title={t("advancedSearch.modal.resetAttrTitle")}
      open={openModal}
      onClose={() => setOpenModal(false)}
    >
      <AutocompleteWithAllSelector
        selectAllLabel={t("advancedSearch.page.selectAll")}
        options={attrNames}
        value={selectedAttrNames}
        onChange={(_, value: Array<string>) =>
          setOrderedColumns((current) => [
            ...current.filter(
              (name) => name === ENTRY_NAME_SORT_TARGET || value.includes(name),
            ),
            ...value.filter((name) => !current.includes(name)),
          ])
        }
        renderInput={(params) => (
          <TextField
            {...params}
            variant="outlined"
            placeholder={t("advancedSearch.modal.selectAttrPlaceholder")}
          />
        )}
        multiple
        sx={{ width: "100%", margin: "20px 0" }}
      />
      <Box>
        <Typography>{t("advancedSearch.modal.columnOrder")}</Typography>
        <List dense aria-label={t("advancedSearch.modal.columnOrder")}>
          {orderedColumns.map((name) => (
            <ListItem
              key={name}
              data-selected-attribute={name}
              sx={{
                border: "1px solid",
                borderColor:
                  dropTargetAttrName === name ? "primary.main" : "divider",
                borderRadius: 1,
                mb: 0.5,
              }}
              onDragOver={(event) => {
                if (draggedAttrName && draggedAttrName !== name) {
                  event.preventDefault();
                  event.dataTransfer.dropEffect = "move";
                  setDropTargetAttrName(name);
                }
              }}
              onDragLeave={() => setDropTargetAttrName(null)}
              onDrop={(event) => {
                event.preventDefault();
                if (draggedAttrName) reorderColumns(draggedAttrName, name);
                setDraggedAttrName(null);
                setDropTargetAttrName(null);
              }}
            >
              <IconButton
                size="small"
                draggable
                aria-label={t("advancedSearch.modal.moveAttribute", {
                  name:
                    name === ENTRY_NAME_SORT_TARGET
                      ? t("advancedSearch.tableHead.entryName")
                      : name,
                })}
                onDragStart={(event) => {
                  event.dataTransfer.effectAllowed = "move";
                  event.dataTransfer.setData("text/plain", name);
                  setDraggedAttrName(name);
                }}
                onDragEnd={() => {
                  setDraggedAttrName(null);
                  setDropTargetAttrName(null);
                }}
                sx={{ cursor: "grab", mr: 1 }}
              >
                <DragIndicatorIcon fontSize="small" />
              </IconButton>
              <ListItemText
                primary={
                  name === ENTRY_NAME_SORT_TARGET
                    ? t("advancedSearch.tableHead.entryName")
                    : name
                }
              />
            </ListItem>
          ))}
        </List>
      </Box>
      <Box display="flex" justifyContent="center">
        <Box>
          {t("advancedSearch.modal.includeReferral")}
          <Checkbox
            checked={hasReferral}
            onChange={(e) => setHasReferral(e.target.checked)}
          />
        </Box>
      </Box>
      <Box display="flex" justifyContent="flex-end" my="8px">
        <Button
          variant="contained"
          color="secondary"
          sx={{ mx: "4px" }}
          onClick={handleUpdatePageURL}
        >
          {t("common.save")}
        </Button>
        <Button
          variant="outlined"
          color="primary"
          sx={{ mx: "4px" }}
          onClick={() => setOpenModal(false)}
        >
          {t("common.cancel")}
        </Button>
      </Box>
    </AironeModal>
  );
};

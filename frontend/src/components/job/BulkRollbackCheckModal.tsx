import {
  Box,
  Button,
  Dialog,
  DialogActions,
  DialogContent,
  DialogTitle,
  LinearProgress,
  Table,
  TableBody,
  TableCell,
  TableContainer,
  TableHead,
  TableRow,
  Typography,
} from "@mui/material";
import { useSnackbar } from "notistack";
import { FC, useEffect, useState } from "react";
import { useNavigate } from "react-router";

import {
  BulkRollbackCheck,
  BulkRollbackCheckValue,
} from "apiclient/autogenerated";
import { AironeTableHeadCell } from "components/common/AironeTableHeadCell";
import { AironeTableHeadRow } from "components/common/AironeTableHeadRow";
import { useTranslation } from "hooks/useTranslation";
import { aironeApiClient } from "repository/AironeApiClient";
import { formatDateTime } from "services/DateUtil";

const formatRollbackValue = (value: unknown): string => {
  if (value === null || value === undefined) return "";
  if (typeof value === "string") return value;
  if (typeof value === "number" || typeof value === "boolean") {
    return String(value);
  }
  if (Array.isArray(value)) return value.map(formatRollbackValue).join(", ");
  return JSON.stringify(value);
};

const ValueCell: FC<{ value: BulkRollbackCheckValue | null }> = ({ value }) => (
  <Typography sx={{ whiteSpace: "pre-wrap", overflowWrap: "anywhere" }}>
    {value ? formatRollbackValue(value.value) || "-" : "-"}
  </Typography>
);

interface Props {
  jobId: number;
  onClose: () => void;
}

type CheckState =
  | { status: "loading" }
  | { status: "error" }
  | { status: "loaded"; data: BulkRollbackCheck };

export const BulkRollbackCheckModal: FC<Props> = ({ jobId, onClose }) => {
  const { t } = useTranslation();
  // The modal is mounted only while open, so the initial state is the loading state.
  const [state, setState] = useState<CheckState>({ status: "loading" });
  const [submitting, setSubmitting] = useState(false);
  const navigate = useNavigate();
  const { enqueueSnackbar } = useSnackbar();

  useEffect(() => {
    let cancelled = false;
    aironeApiClient
      .getBulkRollbackCheck(jobId)
      .then((data) => {
        if (!cancelled) setState({ status: "loaded", data });
      })
      .catch(() => {
        if (!cancelled) setState({ status: "error" });
      });
    return () => {
      cancelled = true;
    };
  }, [jobId]);

  const rollbackDisabled =
    submitting ||
    state.status !== "loaded" ||
    state.data.items.length === 0 ||
    state.data.hasAlreadyBeenRolledBack;

  const handleRollback = async (skipUpdated?: boolean) => {
    setSubmitting(true);
    try {
      const newJobId = await aironeApiClient.rollbackBulkUpdate(
        jobId,
        skipUpdated,
      );
      enqueueSnackbar(
        t("job.rollbackCheck.rollbackStarted", { jobId: newJobId }),
        {
          variant: "success",
        },
      );
      onClose();
      navigate(0);
    } catch {
      enqueueSnackbar(t("job.rollbackCheck.rollbackFailed"), {
        variant: "error",
      });
      setSubmitting(false);
    }
  };

  return (
    <Dialog open onClose={onClose} maxWidth="lg" fullWidth>
      <DialogTitle>{t("job.rollbackCheck.title")}</DialogTitle>
      <DialogContent>
        {state.status === "loading" && <LinearProgress />}
        {state.status === "error" && (
          <Typography color="error">
            {t("job.rollbackCheck.loadFailed")}
          </Typography>
        )}
        {state.status === "loaded" && (
          <Box display="flex" flexDirection="column" gap="12px">
            <Typography variant="body2">
              {t("job.rollbackCheck.executedInfo", {
                datetime: formatDateTime(state.data.executedAt),
                user: state.data.executedUser,
              })}
            </Typography>
            {state.data.items.length === 0 ? (
              <Typography>{t("job.rollbackCheck.noItems")}</Typography>
            ) : (
              <TableContainer>
                <Table size="small">
                  <TableHead>
                    <AironeTableHeadRow>
                      <AironeTableHeadCell>
                        {t("job.rollbackCheck.entryColumn")}
                      </AironeTableHeadCell>
                      <AironeTableHeadCell>
                        {t("job.rollbackCheck.attrColumn")}
                      </AironeTableHeadCell>
                      <AironeTableHeadCell>
                        {t("job.rollbackCheck.beforeColumn")}
                      </AironeTableHeadCell>
                      <AironeTableHeadCell>
                        {t("job.rollbackCheck.afterColumn")}
                      </AironeTableHeadCell>
                      <AironeTableHeadCell>
                        {t("job.rollbackCheck.currentColumn")}
                      </AironeTableHeadCell>
                      <AironeTableHeadCell>
                        {t("job.rollbackCheck.currentSetAtColumn")}
                      </AironeTableHeadCell>
                      <AironeTableHeadCell>
                        {t("job.rollbackCheck.currentSetByColumn")}
                      </AironeTableHeadCell>
                    </AironeTableHeadRow>
                  </TableHead>
                  <TableBody>
                    {state.data.items.map((item) => (
                      <TableRow
                        key={`${item.entryId}-${item.attrId}`}
                        // Rows that can no longer be rolled back were changed again after the bulk update.
                        sx={
                          item.rollbackable
                            ? undefined
                            : { backgroundColor: "#BBDEFB" }
                        }
                      >
                        <TableCell>{item.entryName}</TableCell>
                        <TableCell>{item.attrName}</TableCell>
                        <TableCell>
                          <ValueCell value={item.before} />
                        </TableCell>
                        <TableCell>
                          <ValueCell value={item.after} />
                        </TableCell>
                        <TableCell>
                          <ValueCell value={item.current} />
                        </TableCell>
                        <TableCell>
                          {item.current
                            ? formatDateTime(item.current.createdTime)
                            : "-"}
                        </TableCell>
                        <TableCell>
                          {item.current?.createdUser ?? "-"}
                        </TableCell>
                      </TableRow>
                    ))}
                  </TableBody>
                </Table>
              </TableContainer>
            )}
            {state.data.items.length > 0 && (
              <Typography variant="caption" color="text.secondary">
                {t("job.rollbackCheck.highlightLegend")}
              </Typography>
            )}
          </Box>
        )}
      </DialogContent>
      <DialogActions>
        {state.status === "loaded" && state.data.hasAlreadyBeenRolledBack && (
          <Typography variant="body2" color="error" sx={{ mr: 1 }}>
            {t("job.rollbackCheck.alreadyRolledBack")}
          </Typography>
        )}
        <Button
          variant="contained"
          color="secondary"
          disabled={rollbackDisabled}
          onClick={() => handleRollback(true)}
        >
          {t("job.rollbackCheck.rollbackWithSkip")}
        </Button>
        <Button
          variant="contained"
          color="warning"
          disabled={rollbackDisabled}
          onClick={() => handleRollback(undefined)}
        >
          {t("job.rollbackCheck.rollbackWithoutSkip")}
        </Button>
        <Button variant="outlined" disabled={submitting} onClick={onClose}>
          {t("common.cancel")}
        </Button>
      </DialogActions>
    </Dialog>
  );
};

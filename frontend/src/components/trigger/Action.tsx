import CancelIcon from "@mui/icons-material/Cancel";
import DeleteOutlineIcon from "@mui/icons-material/DeleteOutline";
import {
  Box,
  Checkbox,
  IconButton,
  List,
  ListItem,
  MenuItem,
  Select,
  TableCell,
  TableRow,
  TextField,
} from "@mui/material";
import { styled } from "@mui/material/styles";
import { FC } from "react";
import { Control, Controller, useFieldArray, useWatch } from "react-hook-form";

import { Schema } from "./TriggerFormSchema";

import {
  EntityDetail,
  EntryAttributeTypeTypeEnum,
  GetEntryAttrReferral,
} from "apiclient/autogenerated";
import {
  AddRowButton,
  stripeFor,
  useInsertedRowFocus,
} from "components/common/RowInsertion";
import { ReferralsAutocomplete } from "components/entry/entryForm/ReferralsAutocomplete";
import { useTranslation } from "hooks/useTranslation";
import { isSupportedType } from "services/trigger/Edit";

interface Props {
  index: number;
  control: Control<Schema>;
  remove: (index: number) => void;
  entity: EntityDetail;
}

interface PropsActionValue {
  indexAction: number;
  control: Control<Schema>;
  entity: EntityDetail;
  attrId: number;
}

interface PropsActionValueComponent {
  // The 'indexAction' indicatates what number of action column
  indexAction: number;
  // The 'indexActionValue' indicatates what number of input form in the action column
  indexActionValue: number;
  control: Control<Schema>;
}

interface PropsActionValueObjectValueComponent
  extends PropsActionValueComponent {
  attrId: number;
}

interface PropsActionValueInputForm
  extends PropsActionValueObjectValueComponent {
  entity: EntityDetail;
  handleDelInputValue: (index: number) => void;
}

const StyledBox = styled(Box)(({}) => ({
  display: "flex",
  width: "100%",
  gap: "0 12px",
}));

const NamedObjectBox = styled(Box)(({}) => ({
  display: "flex",
  alignItems: "flex-end",
  gap: "0 12px",
  width: "100%",
}));
const FlexBox = styled(Box)(({}) => ({
  display: "flex",
  flexDirection: "column",
}));
const NameBox = styled(Box)(({}) => ({
  width: "150px",
}));
const StyledList = styled(List)(({}) => ({
  padding: "0",
}));

const StyledListItem = styled(ListItem)(({}) => ({
  padding: "0",
}));

const ActionValueAsString: FC<PropsActionValueComponent> = ({
  indexAction,
  indexActionValue,
  control,
}) => {
  return (
    <Controller
      name={`actions.${indexAction}.values.${indexActionValue}.strCond`}
      control={control}
      render={({ field }) => {
        return <TextField {...field} variant="standard" fullWidth />;
      }}
    />
  );
};

const ActionValueAsBoolean: FC<PropsActionValueComponent> = ({
  indexAction,
  indexActionValue,
  control,
}) => {
  return (
    <Controller
      name={`actions.${indexAction}.values.${indexActionValue}.boolCond`}
      control={control}
      render={({ field }) => (
        <Checkbox
          checked={field.value}
          onChange={(e) => field.onChange(e.target.checked)}
        />
      )}
    />
  );
};

const ActionValueAsObject: FC<PropsActionValueObjectValueComponent> = ({
  indexAction,
  indexActionValue,
  control,
  attrId,
}) => {
  return (
    <Controller
      name={`actions.${indexAction}.values.${indexActionValue}.refCond`}
      control={control}
      render={({ field }) => (
        <ReferralsAutocomplete
          attrId={attrId}
          value={field.value}
          handleChange={(v) => {
            field.onChange({
              id: (v as GetEntryAttrReferral).id,
              name: (v as GetEntryAttrReferral).name,
              schema: {
                id: 0,
                name: "",
              },
            });
          }}
          multiple={false}
        />
      )}
    />
  );
};

const ActionValueAsName: FC<PropsActionValueObjectValueComponent> = ({
  indexAction,
  indexActionValue,
  control,
  attrId,
}) => {
  return (
    <NamedObjectBox>
      <FlexBox>
        <NameBox>
          <Controller
            name={`actions.${indexAction}.values.${indexActionValue}.strCond`}
            control={control}
            render={({ field }) => {
              return <TextField {...field} variant="standard" fullWidth />;
            }}
          />
        </NameBox>
      </FlexBox>
      <Box flexGrow={1}>
        <Controller
          name={`actions.${indexAction}.values.${indexActionValue}.refCond`}
          control={control}
          render={({ field }) => (
            <ReferralsAutocomplete
              attrId={attrId}
              value={field.value}
              handleChange={(v) => {
                field.onChange({
                  id: (v as GetEntryAttrReferral).id,
                  name: (v as GetEntryAttrReferral).name,
                  schema: {
                    id: 0,
                    name: "",
                  },
                });
              }}
              multiple={false}
            />
          )}
        />
      </Box>
    </NamedObjectBox>
  );
};

const ActionValueInputForm: FC<PropsActionValueInputForm> = ({
  indexAction,
  indexActionValue,
  control,
  entity,
  attrId,
  handleDelInputValue,
}) => {
  const { t } = useTranslation();
  const attrInfo = entity.attrs.find((attr) => attr.id === attrId);
  switch (attrInfo?.type) {
    case EntryAttributeTypeTypeEnum.STRING:
    case EntryAttributeTypeTypeEnum.TEXT:
      return (
        <ActionValueAsString
          indexAction={indexAction}
          indexActionValue={indexActionValue}
          control={control}
        />
      );

    case EntryAttributeTypeTypeEnum.ARRAY_STRING:
      return (
        <StyledBox>
          <ActionValueAsString
            indexAction={indexAction}
            indexActionValue={indexActionValue}
            control={control}
          />
          <IconButton
            aria-label={t("trigger.form.deleteActionValue", {
              value: indexActionValue + 1,
            })}
            onClick={() => handleDelInputValue(indexActionValue)}
          >
            <CancelIcon />
          </IconButton>
        </StyledBox>
      );

    case EntryAttributeTypeTypeEnum.BOOLEAN:
      return (
        <ActionValueAsBoolean
          indexAction={indexAction}
          indexActionValue={indexActionValue}
          control={control}
        />
      );

    case EntryAttributeTypeTypeEnum.OBJECT:
      return (
        <ActionValueAsObject
          attrId={attrId}
          indexAction={indexAction}
          indexActionValue={indexActionValue}
          control={control}
        />
      );

    case EntryAttributeTypeTypeEnum.NAMED_OBJECT:
      return (
        <ActionValueAsName
          attrId={attrId}
          indexAction={indexAction}
          indexActionValue={indexActionValue}
          control={control}
        />
      );

    case EntryAttributeTypeTypeEnum.ARRAY_OBJECT:
      return (
        <StyledBox>
          <ActionValueAsObject
            attrId={attrId}
            indexAction={indexAction}
            indexActionValue={indexActionValue}
            control={control}
          />
          <IconButton
            aria-label={t("trigger.form.deleteActionValue", {
              value: indexActionValue + 1,
            })}
            onClick={() => handleDelInputValue(indexActionValue)}
          >
            <CancelIcon />
          </IconButton>
        </StyledBox>
      );

    case EntryAttributeTypeTypeEnum.ARRAY_NAMED_OBJECT:
      return (
        <StyledBox>
          <>
            <ActionValueAsName
              attrId={attrId}
              indexAction={indexAction}
              indexActionValue={indexActionValue}
              control={control}
            />
          </>
          <IconButton
            aria-label={t("trigger.form.deleteActionValue", {
              value: indexActionValue + 1,
            })}
            onClick={() => handleDelInputValue(indexActionValue)}
          >
            <CancelIcon />
          </IconButton>
        </StyledBox>
      );
  }
  return null;
};

/** Attribute types whose action can hold several values. */
const MULTI_VALUE_TYPES: ReadonlySet<number> = new Set([
  EntryAttributeTypeTypeEnum.ARRAY_STRING,
  EntryAttributeTypeTypeEnum.ARRAY_OBJECT,
  EntryAttributeTypeTypeEnum.ARRAY_NAMED_OBJECT,
]);

const ActionValue: FC<PropsActionValue> = ({
  indexAction,
  control,
  entity,
  attrId,
}) => {
  const { fields, insert, remove } = useFieldArray({
    control,
    name: `actions.${indexAction}.values`,
    keyName: "key", // NOTE: attr has 'id' field conflicts default key name
  });

  const { t } = useTranslation();
  const focusInsertedRow = useInsertedRowFocus(`action-values-${indexAction}`);
  // Single-value action types keep a single input, exactly as before: only
  // array types can hold more than one value.
  const canHoldMultipleValues = MULTI_VALUE_TYPES.has(
    entity.attrs.find((attr) => attr.id === attrId)?.type ?? -1,
  );

  const emptyActionValue = () => ({
    id: 0,
    strCond: "",
    refCond: null,
  });

  const handleAddActionValue = (index: number) => {
    insert(index, emptyActionValue());
    focusInsertedRow(index);
  };

  // Keep at least one (empty) value. An action without any value renders no
  // input once its attribute is switched to a single-value type, and such an
  // action is silently dropped from the request on save.
  const handleDelActionValue = (index: number) => {
    remove(index);
    fields.length === 1 && insert(0, emptyActionValue());
  };

  return (
    <StyledList data-testid={`action-values-${indexAction}`}>
      {fields.map((actionValueField, indexActionValue) => {
        return (
          <StyledListItem
            key={actionValueField.key}
            data-list-id={`action-values-${indexAction}`}
            data-row-index={indexActionValue}
          >
            <ActionValueInputForm
              indexAction={indexAction}
              indexActionValue={indexActionValue}
              control={control}
              entity={entity}
              attrId={attrId}
              handleDelInputValue={handleDelActionValue}
            />
          </StyledListItem>
        );
      })}
      {canHoldMultipleValues && (
        <StyledListItem>
          <AddRowButton
            onAdd={() => handleAddActionValue(fields.length)}
            label={t("trigger.form.appendActionValue")}
            ariaLabel={t("trigger.form.appendActionValueAriaLabel", {
              row: indexAction + 1,
            })}
            testId={`append-action-value-${indexAction}`}
          />
        </StyledListItem>
      )}
    </StyledList>
  );
};

export const Action: FC<Props> = ({ index, control, remove, entity }) => {
  const { t } = useTranslation();
  const attrId = useWatch({
    control,
    name: `actions.${index}.attr.id`,
  });
  return (
    <TableRow
      data-list-id="trigger-actions"
      data-row-index={index}
      data-stripe={stripeFor(index)}
    >
      <TableCell>
        <Controller
          name={`actions.${index}.attr.id`}
          control={control}
          render={({ field }) => (
            <Select
              {...field}
              id={`action-attr-${index}`}
              labelId="action-attr-header"
              size="small"
              fullWidth
            >
              <MenuItem key={0} value={0} disabled hidden />
              {entity.attrs
                .filter((attr) => isSupportedType(attr))
                .map((attr) => (
                  <MenuItem key={attr.id} value={attr.id}>
                    {attr.name}
                  </MenuItem>
                ))}
            </Select>
          )}
        />
      </TableCell>
      <TableCell>
        <ActionValue
          indexAction={index}
          control={control}
          attrId={attrId}
          entity={entity}
        />
      </TableCell>
      <TableCell>
        <IconButton
          data-testid={`delete-action-${index}`}
          aria-label={t("trigger.form.deleteAction", { row: index + 1 })}
          onClick={() => remove(index)}
        >
          <DeleteOutlineIcon />
        </IconButton>
      </TableCell>
    </TableRow>
  );
};

import { FC, Fragment } from "react";
import { Control, useFieldArray } from "react-hook-form";

import { Action } from "./Action";
import { Schema } from "./TriggerFormSchema";

import { EntityDetail } from "apiclient/autogenerated";
import {
  AppendRow,
  InsertBandRow,
  useInsertedRowFocus,
} from "components/common/RowInsertion";
import { useTranslation } from "hooks/useTranslation";

interface Props {
  control: Control<Schema>;
  entity: EntityDetail;
}

export const Actions: FC<Props> = ({ control, entity }) => {
  const { fields, insert, remove } = useFieldArray({
    control,
    name: "actions",
    keyName: "key", // NOTE: attr has 'id' field conflicts default key name
  });

  const { t } = useTranslation();
  const focusInsertedRow = useInsertedRowFocus("trigger-actions");

  const handleInsertAction = (index: number) => {
    insert(index, {
      id: 0,
      attr: {
        id: 0,
        name: "",
        type: 0,
      },
      values: [
        {
          id: 0,
          strCond: "",
          refCond: null,
          boolCond: undefined,
        },
      ],
    });
    focusInsertedRow(index);
  };

  return (
    <>
      {fields.map((actionField, index) => (
        <Fragment key={actionField.key}>
          <InsertBandRow
            colSpan={3}
            index={index}
            ariaLabel={t("trigger.form.insertActionBefore", { row: index + 1 })}
            onInsert={handleInsertAction}
            testId={`insert-band-action-${index}`}
          />
          <Action
            index={index}
            control={control}
            remove={remove}
            entity={entity}
          />
        </Fragment>
      ))}
      <AppendRow
        colSpan={3}
        onAdd={() => handleInsertAction(fields.length)}
        label={t("trigger.form.appendAction")}
        testId="append-row-action"
      />
    </>
  );
};

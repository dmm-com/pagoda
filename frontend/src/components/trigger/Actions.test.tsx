/**
 */

import { fireEvent, render, screen, within } from "@testing-library/react";
import { FC } from "react";
import { useForm } from "react-hook-form";

import { TestWrapper } from "../../TestWrapper";

import { Actions } from "./Actions";
import { Schema } from "./TriggerFormSchema";

import {
  EntityDetail,
  EntryAttributeTypeTypeEnum,
} from "apiclient/autogenerated";
import { ACLType } from "services/ACLUtil";

describe("ActionForm", () => {
  const entity: EntityDetail = {
    id: 1,
    name: "entity1",
    isToplevel: false,
    permission: ACLType.Full,
    attrs: [
      EntryAttributeTypeTypeEnum.STRING,
      EntryAttributeTypeTypeEnum.ARRAY_STRING,
      EntryAttributeTypeTypeEnum.BOOLEAN,
      EntryAttributeTypeTypeEnum.OBJECT,
      EntryAttributeTypeTypeEnum.ARRAY_OBJECT,
      EntryAttributeTypeTypeEnum.NAMED_OBJECT,
      EntryAttributeTypeTypeEnum.ARRAY_NAMED_OBJECT,
    ].map((type, index) => ({
      id: index + 1,
      name: `attr${index + 1}`,
      type,
      index,
      note: "",
      isWritable: true,
      isMandatory: false,
      isDeleteInChain: false,
      isSummarized: false,
      referral: [],
    })),
    webhooks: [],
    isolationRules: [],
    deleteChainExcludeEntities: [],
    hasOngoingChanges: false,
  };

  const defaultValues: Schema = {
    id: 1,
    entity: {
      id: 1,
      name: "entity1",
      isPublic: true,
      permission: ACLType.Full,
    },
    conditions: [],
    actions: [
      // string-like
      {
        id: 1,
        attr: {
          id: 1,
          name: "attr1",
          type: EntryAttributeTypeTypeEnum.STRING,
        },
        values: [
          {
            id: 1,
            strCond: "str cond",
            refCond: null,
          },
        ],
      },
      {
        id: 2,
        attr: {
          id: 2,
          name: "attr2",
          type: EntryAttributeTypeTypeEnum.ARRAY_STRING,
        },
        values: [
          {
            id: 1,
            strCond: "str cond 1",
            refCond: null,
          },
          {
            id: 2,
            strCond: "str cond 2",
            refCond: null,
          },
        ],
      },

      // boolean
      {
        id: 3,
        attr: {
          id: 3,
          name: "attr3",
          type: EntryAttributeTypeTypeEnum.BOOLEAN,
        },
        values: [
          {
            id: 1,
            strCond: null,
            refCond: null,
            boolCond: true,
          },
        ],
      },

      // object-like
      {
        id: 4,
        attr: {
          id: 4,
          name: "attr4",
          type: EntryAttributeTypeTypeEnum.OBJECT,
        },
        values: [
          {
            id: 1,
            strCond: null,
            refCond: {
              id: 101,
              name: "ref1",
              schema: {
                id: 101,
                name: "ref1",
              },
            },
          },
        ],
      },
      {
        id: 5,
        attr: {
          id: 5,
          name: "attr5",
          type: EntryAttributeTypeTypeEnum.ARRAY_OBJECT,
        },
        values: [
          {
            id: 1,
            strCond: null,
            refCond: {
              id: 101,
              name: "ref1",
              schema: {
                id: 101,
                name: "ref1",
              },
            },
          },
          {
            id: 2,
            strCond: null,
            refCond: {
              id: 102,
              name: "ref2",
              schema: {
                id: 102,
                name: "ref2",
              },
            },
          },
        ],
      },

      // named-object-like
      {
        id: 6,
        attr: {
          id: 6,
          name: "attr6",
          type: EntryAttributeTypeTypeEnum.NAMED_OBJECT,
        },
        values: [
          {
            id: 1,
            strCond: "name",
            refCond: {
              id: 101,
              name: "ref1",
              schema: {
                id: 101,
                name: "ref1",
              },
            },
          },
        ],
      },
      {
        id: 7,
        attr: {
          id: 7,
          name: "attr7",
          type: EntryAttributeTypeTypeEnum.ARRAY_NAMED_OBJECT,
        },
        values: [
          {
            id: 1,
            strCond: "name1",
            refCond: {
              id: 101,
              name: "ref1",
              schema: {
                id: 101,
                name: "ref1",
              },
            },
          },
          {
            id: 2,
            strCond: "name2",
            refCond: {
              id: 102,
              name: "ref2",
              schema: {
                id: 102,
                name: "ref2",
              },
            },
          },
        ],
      },
    ],
  };

  test("renders attribute based fields", () => {
    const Wrapper: FC = () => {
      const { control } = useForm<Schema>({
        defaultValues,
      });
      return <Actions control={control} entity={entity} />;
    };

    render(<Wrapper />, {
      wrapper: TestWrapper,
    });

    // Insertion bands and the append row are table rows too; only content rows
    // carry the list marker.
    const rows = screen
      .queryAllByRole("row")
      .filter((row) => row.getAttribute("data-list-id") === "trigger-actions");
    expect(rows).toHaveLength(7);

    // string
    const row0 = rows[0];
    expect(within(row0).getByText("attr1")).toBeInTheDocument();
    expect(within(row0).getByDisplayValue("str cond")).toBeInTheDocument();

    // array-string
    const row1 = rows[1];
    expect(within(row1).getByText("attr2")).toBeInTheDocument();
    expect(within(row1).getByDisplayValue("str cond 1")).toBeInTheDocument();
    expect(within(row1).getByDisplayValue("str cond 2")).toBeInTheDocument();

    // boolean
    const row2 = rows[2];
    expect(within(row2).getByText("attr3")).toBeInTheDocument();
    expect(within(row2).getByRole("checkbox")).toBeChecked();

    // object
    const row3 = rows[3];
    expect(within(row3).getByText("attr4")).toBeInTheDocument();
    expect(within(row3).getByDisplayValue("ref1")).toBeInTheDocument();

    // array-object
    const row4 = rows[4];
    expect(within(row4).getByText("attr5")).toBeInTheDocument();
    expect(within(row4).getByDisplayValue("ref1")).toBeInTheDocument();
    expect(within(row4).getByDisplayValue("ref2")).toBeInTheDocument();

    // named-object
    const row5 = rows[5];
    expect(within(row5).getByText("attr6")).toBeInTheDocument();
    expect(within(row5).getByDisplayValue("name")).toBeInTheDocument();
    expect(within(row5).getByDisplayValue("ref1")).toBeInTheDocument();

    // array-named-object
    const row6 = rows[6];
    expect(within(row6).getByText("attr7")).toBeInTheDocument();
    expect(within(row6).getByDisplayValue("name1")).toBeInTheDocument();
    expect(within(row6).getByDisplayValue("ref1")).toBeInTheDocument();
    expect(within(row6).getByDisplayValue("name2")).toBeInTheDocument();
    expect(within(row6).getByDisplayValue("ref2")).toBeInTheDocument();
  });

  test("keeps one empty value when the last value is deleted", () => {
    const Wrapper: FC = () => {
      const { control } = useForm<Schema>({
        defaultValues,
      });
      return <Actions control={control} entity={entity} />;
    };

    render(<Wrapper />, {
      wrapper: TestWrapper,
    });

    // array-string action, which starts with two values
    const values = screen.getByTestId("action-values-1");
    const deleteFirstValue = () =>
      fireEvent.click(within(values).getAllByRole("button")[0]);

    deleteFirstValue();
    expect(within(values).getAllByRole("textbox")).toHaveLength(1);
    expect(within(values).getByDisplayValue("str cond 2")).toBeInTheDocument();

    // An action must never end up without any value: it would render no input
    // after switching to a single-value attribute and be dropped on save.
    deleteFirstValue();
    expect(within(values).getAllByRole("textbox")).toHaveLength(1);
    expect(within(values).getByRole("textbox")).toHaveValue("");
  });
});

import { FC, Fragment } from "react";
import { Control, useFieldArray } from "react-hook-form";

import { Condition } from "./Condition";
import { Schema } from "./TriggerFormSchema";

import { EntityDetail } from "apiclient/autogenerated";
import {
  AppendRow,
  InsertBandRow,
  useInsertedRowFocus,
} from "components/common/RowInsertion";
import { useTranslation } from "hooks/useTranslation";

interface Props {
  control: Control<Schema>;
  entity: EntityDetail;
}

export const Conditions: FC<Props> = ({ control, entity }) => {
  const { fields, insert, remove } = useFieldArray({
    control,
    name: "conditions",
    keyName: "key", // NOTE: attr has 'id' field conflicts default key name
  });

  const { t } = useTranslation();
  const focusInsertedRow = useInsertedRowFocus("trigger-conditions");

  const handleInsertCondition = (index: number) => {
    insert(index, {
      id: 0,
      attr: {
        id: 0,
        name: "",
        type: 0,
      },
      strCond: "",
      refCond: null,
      boolCond: undefined,
      isUnmatch: false,
    });
    focusInsertedRow(index);
  };

  return (
    <>
      {fields.map((condField, index) => (
        <Fragment key={condField.key}>
          <InsertBandRow
            colSpan={4}
            index={index}
            ariaLabel={t("trigger.form.insertConditionBefore", {
              row: index + 1,
            })}
            onInsert={handleInsertCondition}
            testId={`insert-band-condition-${index}`}
          />
          <Condition
            index={index}
            control={control}
            remove={remove}
            entity={entity}
          />
        </Fragment>
      ))}
      <AppendRow
        colSpan={4}
        onAdd={() => handleInsertCondition(fields.length)}
        label={t("trigger.form.appendCondition")}
        testId="append-row-condition"
      />
    </>
  );
};

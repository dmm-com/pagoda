/**
 */

import { render, screen, within } from "@testing-library/react";
import { FC } from "react";
import { useForm } from "react-hook-form";

import { TestWrapper } from "../../TestWrapper";

import { Conditions } from "./Conditions";
import { Schema } from "./TriggerFormSchema";

import {
  EntityDetail,
  EntryAttributeTypeTypeEnum,
} from "apiclient/autogenerated";
import { ACLType } from "services/ACLUtil";

describe("Conditions", () => {
  const entity: EntityDetail = {
    id: 1,
    name: "entity1",
    isToplevel: false,
    permission: ACLType.Full,
    attrs: [
      EntryAttributeTypeTypeEnum.STRING,
      EntryAttributeTypeTypeEnum.BOOLEAN,
      EntryAttributeTypeTypeEnum.OBJECT,
      EntryAttributeTypeTypeEnum.NAMED_OBJECT,
    ].map((type, index) => ({
      id: index + 1,
      name: `attr${index + 1}`,
      type,
      index,
      note: "",
      isWritable: true,
      isMandatory: false,
      isDeleteInChain: false,
      isSummarized: false,
      referral: [],
    })),
    webhooks: [],
    isolationRules: [],
    deleteChainExcludeEntities: [],
    hasOngoingChanges: false,
  };

  const defaultValues: Schema = {
    id: 1,
    entity: {
      id: 1,
      name: "entity1",
      isPublic: true,
      permission: ACLType.Full,
    },
    conditions: [
      {
        id: 1,
        attr: {
          id: 1,
          name: "attr1",
          type: EntryAttributeTypeTypeEnum.STRING,
        },
        strCond: "str cond",
        refCond: null,
      },
      {
        id: 2,
        attr: {
          id: 2,
          name: "attr2",
          type: EntryAttributeTypeTypeEnum.BOOLEAN,
        },
        boolCond: true,
        strCond: null,
        refCond: null,
      },
      {
        id: 3,
        attr: {
          id: 3,
          name: "attr3",
          type: EntryAttributeTypeTypeEnum.OBJECT,
        },
        strCond: null,
        refCond: {
          id: 101,
          name: "ref1",
          schema: {
            id: 101,
            name: "ref1",
          },
        },
      },
      {
        id: 4,
        attr: {
          id: 4,
          name: "attr4",
          type: EntryAttributeTypeTypeEnum.NAMED_OBJECT,
        },
        strCond: "name",
        refCond: {
          id: 101,
          name: "ref1",
          schema: {
            id: 101,
            name: "ref1",
          },
        },
      },
    ],
    actions: [],
  };

  test("renders attribute based fields", () => {
    const Wrapper: FC = () => {
      const { control } = useForm<Schema>({
        defaultValues,
      });
      return <Conditions control={control} entity={entity} />;
    };

    render(<Wrapper />, {
      wrapper: TestWrapper,
    });

    // Insertion bands and the append row are table rows too; only content rows
    // carry the list marker.
    const rows = screen
      .queryAllByRole("row")
      .filter(
        (row) => row.getAttribute("data-list-id") === "trigger-conditions",
      );
    expect(rows).toHaveLength(4);

    const row0 = rows[0];
    expect(within(row0).getByText("attr1")).toBeInTheDocument();
    expect(within(row0).getByDisplayValue("str cond")).toBeInTheDocument();

    const row1 = rows[1];
    expect(within(row1).getByText("attr2")).toBeInTheDocument();
    expect(within(row1).getAllByRole("checkbox")[1]).toBeChecked();

    const row2 = rows[2];
    expect(within(row2).getByText("attr3")).toBeInTheDocument();
    expect(within(row2).getByDisplayValue("ref1")).toBeInTheDocument();

    const row3 = rows[3];
    expect(within(row3).getByText("attr4")).toBeInTheDocument();
    expect(within(row3).getByDisplayValue("name")).toBeInTheDocument();
    expect(within(row3).getByDisplayValue("ref1")).toBeInTheDocument();
  });
});
